"""
Part-shape measurements the staged forging variables are defined on (memory/Forging/forging_variables.csv): the fraction of
the surface area that is about a turning axis (surfaceAreaThreshold2D 0.95, surfaceAreaThreshold2_5D 0.75), the ratio of the
largest to the next largest part-box dimension (partLongitudinalRatioThreshold 2), and the holes. They are measurements; the
2D / 2.5D / 3D class and the longitudinal flag are decided downstream against the staged thresholds, because how those classes
combine into the 1 to 12 complexity score is not sourced (v1.1 section 6.2, "NEEDS SOURCE").
"""
from __future__ import annotations

import math
from typing import Any, Dict, List, Optional, Sequence

from shared.machining_geometry import collect_cylinders, part_bounding_box
from shared.solid_measures import measure_solid

from .constants import CANONICAL_AXES, REVOLUTION_AXIS_ANGLE_DEG, REVOLUTION_AXIS_DISTANCE_MM
from .sampling import FaceRecord


def _dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _about_axis(face: Any, kind: str, centre, axis) -> bool:
    """Is this face a surface of revolution about the line through `centre` along `axis`?"""
    from OCC.Core.BRepAdaptor import BRepAdaptor_Surface  # type: ignore
    ad = BRepAdaptor_Surface(face)
    cos_tol = math.cos(math.radians(REVOLUTION_AXIS_ANGLE_DEG))

    def on_line(origin) -> float:
        d = (origin[0] - centre[0], origin[1] - centre[1], origin[2] - centre[2])
        along = _dot(d, axis)
        off = (d[0] - along * axis[0], d[1] - along * axis[1], d[2] - along * axis[2])
        return math.sqrt(_dot(off, off))

    if kind == "plane":  # a disc or annulus perpendicular to the axis is generated by revolution
        n = ad.Plane().Axis().Direction()
        return abs(_dot((n.X(), n.Y(), n.Z()), axis)) >= cos_tol
    if kind in ("cylinder", "cone", "torus"):
        a = {"cylinder": ad.Cylinder, "cone": ad.Cone, "torus": ad.Torus}[kind]().Axis()
    elif kind == "revolution":
        a = ad.AxeOfRevolution()
    elif kind == "sphere":
        c = ad.Sphere().Location()
        return on_line((c.X(), c.Y(), c.Z())) <= REVOLUTION_AXIS_DISTANCE_MM
    else:
        return False
    d, loc = a.Direction(), a.Location()
    return abs(_dot((d.X(), d.Y(), d.Z()), axis)) >= cos_tol and on_line((loc.X(), loc.Y(), loc.Z())) <= REVOLUTION_AXIS_DISTANCE_MM


def revolution_fractions(shape: Any, faces: List[FaceRecord], centre_of_mass) -> Dict[str, Any]:
    total = sum(f.area_mm2 for f in faces) or 1.0
    out = {}
    for name, axis in CANONICAL_AXES.items():
        area = sum(f.area_mm2 for f in faces if _about_axis(f.face, f.surface_type, centre_of_mass, axis))
        out[name] = round(area / total, 6)
    best = max(out, key=lambda k: out[k])
    return {
        "definition": "fraction of the surface area on faces that are surfaces of revolution about the line through the centre of mass along each world axis",
        "by_axis": out,
        "best_axis": best,
        "best_fraction": out[best],
    }


def holes(shape: Any, pull_direction: Sequence[float]) -> List[Dict[str, Any]]:
    """Bores (through and blind) from the shared cylinder collector, measured along the chosen pull direction."""
    bbox = part_bounding_box(shape)
    out = []
    for c in collect_cylinders(shape, tuple(pull_direction), bbox):
        if c["kind"] not in ("through_hole", "blind_hole"):
            continue
        d, depth = c["radius"] * 2.0, c["length"]
        ax = tuple(c["axis"])
        cos = abs(_dot(ax, pull_direction))
        out.append({
            "diameter_mm": round(d, 3),
            "depth_mm": round(depth, 3),
            "length_to_diameter": round(depth / d, 3) if d > 0 else None,
            "blind": c["kind"] == "blind_hole",
            "axis": [round(v, 6) for v in ax],
            "axis_angle_to_pull_deg": round(math.degrees(math.acos(min(1.0, cos))), 3),
            "centroid_mm": [round(v, 3) for v in c["centroid"]],
            "face_indices": list(c.get("face_indices", [])),
        })
    return out


def shape_measures(shape: Any) -> Dict[str, Any]:
    m = measure_solid(shape)
    bb = m["bounding_box"]
    dims = [bb["length"], bb["width"], bb["height"]]
    cm = m["volume_props"].CentreOfMass()
    return {
        "volume_mm3": round(m["volume"], 3),
        "surface_area_mm2": round(m["surface_area"], 3),
        "bounding_box_mm": {"length": dims[0], "width": dims[1], "height": dims[2]},
        "longitudinal_ratio": round(dims[0] / dims[1], 4) if dims[1] > 0 else None,
        "centre_of_mass_mm": [round(cm.X(), 4), round(cm.Y(), 4), round(cm.Z(), 4)],
        "_centre": (cm.X(), cm.Y(), cm.Z()),
        "_volume": m["volume"],
    }
