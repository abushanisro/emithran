/**
 * Platform icon set. Every decorative icon is a duotone: a brand-teal shape
 * behind a stroked glyph (or, for the common ones, a hand-drawn teal + navy
 * pair from duotone-icons.tsx). Components import icons from here instead of
 * 'lucide-react', with the same names and props, so sizes and colour classes
 * set at the call site keep working. Control glyphs (chevrons, check, close,
 * spinner, arrows, grips, menu dots) stay as plain strokes.
 */

export type { LucideIcon, LucideProps };

// A semantic colour class (destructive, success, …) tints the backing shape to
// match instead of using brand teal.
const TINTED = /(?:^|\s)(?:[\w-]+:)*text-(?:destructive|red|rose|green|emerald|success|amber|yellow|orange|warning|blue|sky|info)\b/;

function duo(Glyph: LucideIcon, displayName: string): LucideIcon {
  function DuoGlyph({ className, size = 24, strokeWidth, ...rest }: LucideProps) {
    const tinted = TINTED.test(className ?? '');
    const labelled = rest['aria-label'] !== undefined || rest.role !== undefined;
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        width={size}
        height={size}
        className={className}
        aria-hidden={labelled ? undefined : true}
        {...rest}
      >
        <circle
          cx="8.5"
          cy="8.5"
          r="7"
          fill={tinted ? 'currentColor' : 'var(--duo-back)'}
          fillOpacity={tinted ? 0.2 : 0.6}
        />
        <Glyph size={24} {...(strokeWidth !== undefined ? { strokeWidth } : {})} />
      </svg>
    );
  }
  DuoGlyph.displayName = displayName;
  return DuoGlyph as unknown as LucideIcon;
}

// Hand-drawn pair unless a semantic colour class asks for a tinted glyph.
function hand(Drawn: (props: LucideProps) => React.JSX.Element, Fallback: LucideIcon, displayName: string): LucideIcon {
  function HandDrawn(props: LucideProps) {
    if (TINTED.test(props.className ?? '')) return <Fallback {...props} />;
    return <Drawn {...props} />;
  }
  HandDrawn.displayName = displayName;
  return HandDrawn as unknown as LucideIcon;
}

