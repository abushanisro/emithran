-- migrations/resync-id-sequences.sql: every id sequence at least its table's highest id, never lowered (migrate.ts runs it before migrations).
-- Staging and production were loaded from a baseline whose reference tables held rows inserted with explicit ids while their sequences sat
-- at 1, so the first insert taking a default id (migration 1036) collided with an existing row.
\set ON_ERROR_STOP on

-- behind: rows up to 12050, the sequence still at 1, as on staging
CREATE TABLE public.t_behind (id serial PRIMARY KEY, key text);
INSERT INTO public.t_behind (id, key) SELECT g, 'k' || g FROM generate_series(1, 12050) g;
-- ahead: rows deleted after the sequence moved on; it must not be lowered (a lowered sequence hands out ids again)
CREATE TABLE public.t_ahead (id serial PRIMARY KEY);
INSERT INTO public.t_ahead DEFAULT VALUES; INSERT INTO public.t_ahead DEFAULT VALUES; INSERT INTO public.t_ahead DEFAULT VALUES;
DELETE FROM public.t_ahead WHERE id > 1;
-- empty: nothing to compare with, left as it is
CREATE TABLE public.t_empty (id bigserial PRIMARY KEY);
-- identity columns are sequences too
CREATE TABLE public.t_identity (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
INSERT INTO public.t_identity (id) VALUES (40);

\i /migrations/resync-id-sequences.sql

DO $$
BEGIN
  ASSERT (SELECT last_value FROM public.t_behind_id_seq) = 12050, 'a sequence behind its rows is moved to the highest id';
  INSERT INTO public.t_behind (key) VALUES ('new');
  ASSERT (SELECT max(id) FROM public.t_behind) = 12051, 'the next default id is past every row (the insert that failed on staging)';
  ASSERT (SELECT last_value FROM public.t_ahead_id_seq) = 3, 'a sequence already past its rows is not lowered';
  ASSERT (SELECT is_called FROM public.t_empty_id_seq) = false, 'an empty table''s sequence is untouched';
  INSERT INTO public.t_identity DEFAULT VALUES;
  ASSERT (SELECT max(id) FROM public.t_identity) = 41, 'an identity column is resynced too';
END $$;

-- running it again changes nothing (migrate.ts runs it on every run)
\i /migrations/resync-id-sequences.sql
DO $$ BEGIN
  ASSERT (SELECT last_value FROM public.t_behind_id_seq) = 12051, 'a second run leaves an in-step sequence as it is';
END $$;
