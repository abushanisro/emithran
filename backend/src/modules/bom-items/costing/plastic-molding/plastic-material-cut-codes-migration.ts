// Migration 978: the cut code of each plastic material, from memory/Plastic Modeling/materials_final.csv. The passivation, magnetic particle, carburizing and carbonitriding
// operations decide from the material's cut code (the cutting-parameter code whose integer part is the cut-code family), and 88 of the 318 Plastic & Rubber rows of
// raw_materials had none, so each of those operations stopped at "the material cut code is needed" for a material whose cut code the reference holds. The link is the
// reference material's own sourceName equal to a raw_materials name (case-insensitive, one row on each side), as migration 831 links the injection-molding properties.
// A cut code already on a row is never changed. Pure: the CSV text in, the migration out.

export interface CutCodeRow { sourceName: string; cutCode: number }

/** One CSV row per line, fields split on commas outside quotes, quotes doubled inside a quoted field. */
export function parseCsv(text: string): Array<Record<string, string>> {
  const rows: string[][] = [];
  let field = ''; let row: string[] = []; let quoted = false;
  const src = text.replace(/^﻿/, '');
  for (let i = 0; i < src.length; i++) {
    const c = src[i]!;
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') { field += '"'; i++; } else if (c === '"') quoted = false; else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && src[i + 1] === '\n') i++; row.push(field); field = ''; if (row.length > 1 || row[0] !== '') rows.push(row); row = []; }
    else field += c;
  }
  if (field !== '' || row.length > 0) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header!.map((h, i) => [h, r[i] ?? ''])));
}

/** The reference materials that have a cut code and a source name no other reference material shares (a shared name would be ambiguous: it links to nothing). */
export function cutCodeRows(csv: string): CutCodeRow[] {
  const bySource = new Map<string, number[]>();
  for (const r of parseCsv(csv)) {
    const name = (r['sourceName'] ?? '').trim();
    const code = Number(r['cutCode']);
    if (!name || (r['cutCode'] ?? '') === '' || !Number.isFinite(code)) continue;
    bySource.set(name.toLowerCase(), [...(bySource.get(name.toLowerCase()) ?? []), code]);
  }
  return [...bySource.entries()].filter(([, codes]) => codes.length === 1).map(([sourceName, codes]) => ({ sourceName, cutCode: codes[0]! })).sort((a, b) => a.sourceName.localeCompare(b.sourceName));
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildPlasticMaterialCutCodesMigrationSql(csv: string): string {
  const rows = cutCodeRows(csv);
  return `-- 978: raw_materials plastics carry the cut code of memory/Plastic Modeling/materials_final.csv.
--
-- GENERATED by scripts/generate-plastic-material-cut-codes-migration.ts from memory/Plastic Modeling/materials_final.csv. Do not edit by hand: regenerate.
--
-- ROOT CAUSE
--
-- The passivation, magnetic particle testing, carburizing and carbonitriding operations of the secondary-operations list decide from the material's cut code. 88 of the 318
-- Plastic & Rubber rows of raw_materials had none (the Back cover's "Generic Nylon, Type 11 40% Glass" among them), so those operations stopped at "the material cut code is
-- needed", although the reference holds the cut code of ${rows.length} plastic materials.
--
-- WHAT THIS DOES
--
-- Writes the cut code of each reference material onto the raw_materials row whose name equals the reference material's sourceName (case-insensitive), where that name is one
-- row, and only where the row has no cut code: a cut code already on a row is never changed. One statement, idempotent.

UPDATE raw_materials r
SET cut_code = v.cut_code
FROM (VALUES
${rows.map((x) => `  (${lit(x.sourceName)}, ${x.cutCode})`).join(',\n')}
) AS v(source_name, cut_code)
WHERE lower(r.name) = v.source_name
  AND r.cut_code IS NULL
  AND (SELECT count(*) FROM raw_materials x WHERE lower(x.name) = v.source_name) = 1;
`;
}
