import { domainFieldToRow, type DomainCalculatorSpec } from './domain-calculator-spec';

export interface DomainMigrationText {
  number: number;
  title: string;
  /** The generator script and spec paths, for the header. */
  generator: string;
  specPath: string;
  rootCause: string;
}

const q = (v: string | number | null | undefined) =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `$q$${v}$q$`;

/**
 * The SQL of a domain calculators migration, built from its spec. The domain's
 * generator script writes it to disk; a test asserts the committed migration
 * still equals it. Idempotent: calculators are matched by name, their fields
 * replaced, and the catalog rows of the domain linked to them.
 */
export function buildDomainCalculatorsMigrationSql(spec: DomainCalculatorSpec, text: DomainMigrationText): string {
  const out: string[] = [];
  out.push(`-- ${text.number}: ${text.title}
--
-- GENERATED by ${text.generator} from
-- ${text.specPath}.
-- Do not edit by hand: change the spec and regenerate.
--
-- ROOT CAUSE
--
${text.rootCause.split('\n').map((l) => `-- ${l}`.trimEnd()).join('\n')}
--
-- This migration creates one global calculator per spec entry (inputs are the
-- values the cost engine seeds, each shown with its source in the calculation
-- trace; calculated fields are the formulas the engine evaluates, it holds
-- none) and links every ${spec.processGroup} catalog operation it computes to its
-- calculator in process_calculator_mappings.
--
-- Requires migration 804 (calculators.retired_at).
-- Self-contained, idempotent, post-checked.

BEGIN;
`);

  for (const c of spec.calculators) {
    const rows = c.fields.map((f, i) => domainFieldToRow(f, i + 1));
    out.push(`
-- ${c.name}
DO $calc$
DECLARE v_id UUID;
BEGIN
  SELECT id INTO v_id FROM public.calculators WHERE name = ${q(c.name)} AND user_id IS NULL AND retired_at IS NULL;
  IF v_id IS NULL THEN
    INSERT INTO public.calculators (user_id, name, calc_category, calculator_type, is_template, is_public, is_global, description)
    VALUES (NULL, ${q(c.name)}, 'process', 'single', false, true, true, ${q(c.description)})
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.calculators SET calc_category = 'process', description = ${q(c.description)}, updated_at = now() WHERE id = v_id;
  END IF;

  DELETE FROM public.calculator_fields WHERE calculator_id = v_id;
  INSERT INTO public.calculator_fields
    (calculator_id, field_name, display_label, field_type, unit, data_source, source_table, source_field, default_value, display_order, is_required)
  VALUES
${rows.map((r) => `    (v_id, ${q(r.field_name)}, ${q(r.display_label)}, ${q(r.field_type)}, ${q(r.unit)}, NULL, NULL, NULL, ${q(r.default_value as string | null)}, ${r.display_order}, ${r.field_type !== 'calculated'})`).join(',\n')};

  UPDATE public.process_calculator_mappings
  SET calculator_id = v_id, calculator_name = ${q(c.name)}
  WHERE process_group = ${q(spec.processGroup)} AND operation IN (${c.operations.map((o) => q(o)).join(', ')});
END
$calc$;
`);
  }

  const expected = spec.calculators.map((c) => `(${q(c.name)}, ${c.fields.length}, ${c.operations.length})`).join(',\n    ');
  out.push(`
-- Post-check: every calculator exists once, with all its fields, linked to every operation it computes.
DO $post$
DECLARE bad TEXT;
BEGIN
  SELECT string_agg(e.name, ', ') INTO bad
  FROM (VALUES
    ${expected}
  ) AS e(name, field_count, mapping_count)
  LEFT JOIN public.calculators c ON c.name = e.name AND c.user_id IS NULL AND c.retired_at IS NULL
  WHERE c.id IS NULL
     OR (SELECT count(*) FROM public.calculator_fields f WHERE f.calculator_id = c.id) <> e.field_count
     OR (SELECT count(*) FROM public.process_calculator_mappings m WHERE m.calculator_id = c.id AND m.process_group = ${q(spec.processGroup)}) <> e.mapping_count;
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'migration ${text.number}: calculators incomplete: %', bad;
  END IF;
END
$post$;

COMMIT;
`);
  return out.join('');
}
