import { CASTING_LOOKUP_DATA_SOURCE, dieCastingFieldToRow, loadDieCastingCalculatorSpec, type DieCastingCalculatorSpec } from './die-casting-calculator-spec';

/**
 * The SQL of migrations/893_die_casting_calculators.sql, built from the spec.
 * scripts/generate-die-casting-calculators-migration.ts writes it to disk; a
 * test asserts the committed migration still equals it.
 */
export function buildDieCastingCalculatorsMigrationSql(spec: DieCastingCalculatorSpec = loadDieCastingCalculatorSpec()): string {
  const q = (v: string | number | null | undefined) =>
    v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `$q$${v}$q$`;
  const out: string[] = [];

  out.push(`-- 893: Die casting calculators -- every value the die-casting costing computes
-- (material usage, shot, melting, cycle times, trim force, cores, die tooling)
-- as a real database calculator.
--
-- GENERATED by scripts/generate-die-casting-calculators-migration.ts from
-- src/modules/bom-items/costing/casting/calculators/die-casting-calculators.json.
-- Do not edit by hand: change the spec and regenerate.
--
-- ROOT CAUSE
--
-- The die-casting formulas were held in TypeScript and the Die Casting rows of
-- process_calculator_mappings (migration 844) had calculator_id NULL, so the
-- cost dialogs could not open the calculator behind a line, and the material
-- dialog offered unrelated calculators.
--
-- This migration:
--   1. allows data_source ${CASTING_LOOKUP_DATA_SOURCE} on calculator_fields (a memory/Die Casting
--      variable, lookup table or alloy column, named by source_table / source_field);
--   2. creates one global calculator per die-casting value whose inputs are CAD
--      measurements, alloy and machine values, variables and lookup rows, and whose
--      calculated fields are the formulas the cost engine evaluates -- it holds none;
--   3. links each process calculator to its Die Casting catalog row (migration 844).
--
-- Requires migrations 804 (calculators.retired_at) and 844 (Die Casting catalog rows).
-- Self-contained, idempotent, post-checked.

BEGIN;

DO $pre$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.process_calculator_mappings WHERE process_group = 'Die Casting' AND operation = 'High Pressure Die Casting') THEN
    RAISE EXCEPTION 'migration 893 needs migration 844 applied first (Die Casting catalog rows missing)';
  END IF;
END
$pre$;

ALTER TABLE public.calculator_fields DROP CONSTRAINT IF EXISTS valid_data_source;
ALTER TABLE public.calculator_fields ADD CONSTRAINT valid_data_source CHECK (
  data_source IS NULL OR data_source IN ('lhr', 'mhr', 'raw_materials', 'processes', 'manual', 'sheet_metal_lookup', 'machining_lookup', '${CASTING_LOOKUP_DATA_SOURCE}')
);
`);

  const mapped: string[] = [];
  for (const c of spec.calculators) {
    const rows = c.fields.map((f, i) => dieCastingFieldToRow(f, i + 1));
    out.push(`
-- ${c.name}
DO $calc$
DECLARE v_id UUID;
BEGIN
  SELECT id INTO v_id FROM public.calculators WHERE name = ${q(c.name)} AND user_id IS NULL AND retired_at IS NULL;
  IF v_id IS NULL THEN
    INSERT INTO public.calculators (user_id, name, calc_category, calculator_type, is_template, is_public, is_global, description)
    VALUES (NULL, ${q(c.name)}, ${q(c.category)}, 'single', false, true, true, ${q(c.description)})
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.calculators SET calc_category = ${q(c.category)}, description = ${q(c.description)}, updated_at = now() WHERE id = v_id;
  END IF;

  DELETE FROM public.calculator_fields WHERE calculator_id = v_id;
  INSERT INTO public.calculator_fields
    (calculator_id, field_name, display_label, field_type, unit, data_source, source_table, source_field, default_value, display_order, is_required)
  VALUES
${rows.map((r) => `    (v_id, ${q(r.field_name)}, ${q(r.display_label)}, ${q(r.field_type)}, ${q(r.unit)}, ${q(r.data_source)}, ${q(r.source_table)}, ${q(r.source_field)}, ${q(r.default_value as string | null)}, ${r.display_order}, ${r.field_type !== 'calculated'})`).join(',\n')};

  UPDATE public.process_calculator_mappings
  SET calculator_id = v_id, calculator_name = ${q(c.name)}
  WHERE process_group = 'Die Casting' AND operation = ${q(c.key)};
END
$calc$;
`);
    if (c.category === 'process') mapped.push(c.key);
  }

  const expected = spec.calculators.map((c) => `(${q(c.name)}, ${c.fields.length})`).join(',\n    ');
  out.push(`
-- Post-check: every calculator exists once, with all its fields; every Die Casting
-- catalog row named like a process calculator points at it.
DO $post$
DECLARE bad TEXT;
BEGIN
  SELECT string_agg(e.name, ', ') INTO bad
  FROM (VALUES
    ${expected}
  ) AS e(name, field_count)
  LEFT JOIN public.calculators c ON c.name = e.name AND c.user_id IS NULL AND c.retired_at IS NULL
  WHERE c.id IS NULL
     OR (SELECT count(*) FROM public.calculator_fields f WHERE f.calculator_id = c.id) <> e.field_count;
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'migration 893: calculators incomplete: %', bad;
  END IF;

  SELECT string_agg(m.operation, ', ') INTO bad
  FROM public.process_calculator_mappings m
  WHERE m.process_group = 'Die Casting'
    AND m.operation IN (${mapped.map((k) => q(k)).join(', ')})
    AND m.calculator_id IS NULL;
  IF bad IS NOT NULL THEN
    RAISE EXCEPTION 'migration 893: Die Casting catalog rows without a calculator: %', bad;
  END IF;
END
$post$;

COMMIT;

NOTIFY pgrst, 'reload schema';
`);
  return out.join('');
}
