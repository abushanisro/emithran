-- Purpose: migration 574 added mhr_records.machine_labor_rate_per_hr (this
--          machine's own operator wage rate, baked into the bottom-up
--          formula's fully-burdened rate) as a new, initially-NULL column.
--          memory/sheetmetal/machine/machine_library.csv's own
--          labor_rate_usd_hr column carries real, sourced, category-tiered
--          operator wage data (verified: only 3 distinct values across all
--          281 rows -- 36.3 / 43.21 / 29.95 USD/hr -- each shared by an
--          entire machine category, e.g. all Roll Benders at 43.21, all
--          Cut-To-Length-family machines at 29.95) -- worth backfilling.
--
--          Deliberately NOT backfilling this migration's sibling columns
--          (supplies_cost_per_year, salvage_value_factor_pct,
--          overhead_multiplier, work_center_labor_rate_factor) from the same
--          CSV: verified those four are constant placeholder values across
--          ALL 281 rows (salvage/supplies/overhead_multiplier = 0.0 for
--          every row; work_center_labor_rate_factor is '1.0' or blank for
--          every row) -- i.e. unpopulated reference columns, not real
--          per-machine data. Backfilling them would dress up "no data" as a
--          sourced number (overhead_multiplier=0 would also actively zero
--          out every machine's overhead cost, which is wrong). Leaving them
--          NULL lets mhr-calculation.engine.ts's own documented defaults
--          (1 for multiplier/factor columns, 0 for supplies/salvage) apply
--          honestly instead.
--
--          machine_name is not globally unique in the CSV (12 duplicates,
--          e.g. "Default Press" appears under both "Progressive Die Press"
--          and "Tandem Press") -- verified every duplicate pair shares the
--          identical labor_rate_usd_hr value, so matching by name alone
--          cannot misassign a rate even without a category join.
--
--          IS NULL guard makes this idempotent and never overwrites a real
--          shop-entered machine_labor_rate_per_hr with this benchmark value.
