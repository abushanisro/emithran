/**
 * Writes migration 1106 (the Roto & Blow Molding machines at India rates) from memory/Countries data:
 *   node scripts/generate-roto-blow-machines-migration.js
 * Each India row is its USA twin (migration 862, same machine class and exact name) with the India direct and indirect overhead rates of the
 * export and the India rate of its process's wage grade (memory/Roto & blow molding/roto_blow_molding_wage_grade_associations.csv).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1106_roto_blow_machines_india.sql');

// The machine class migration 862 gave each Roto & Blow Molding process.
const CLASS = {
  'Extrusion Blow Mold': 'roto_blow_molding_extrusion_blow_mold', 'Rotational Mold': 'roto_blow_molding_rotational_mold',
  Router: 'roto_blow_molding_router', Saw: 'roto_blow_molding_saw', Grind: 'roto_blow_molding_grind',
};
// India labour by wage grade (USD/hr): the rates the India rows of each grade carry in HR Rates
// (SELECT DISTINCT wage_grade, usd_labor_rate_per_hr FROM mhr_records WHERE location = 'India' AND wage_grade LIKE '% - Plastic'):
// 2 - Plastic 1.57, 3 - Plastic 1.65, 5 - Plastic 2.15. No India row carries 4 - Plastic: it is interpolated between 3 and 5 at the point
// the USA rate of 4 - Plastic lies between theirs (USA 35.12, 41.80, 45.81: 62.5 % of the way), 1.65 + 0.625 x (2.15 - 1.65) = 1.96.
const INDIA_LABOUR = { '2 - Plastic': 1.57, '4 - Plastic': 1.96 };

const grades = Object.fromEntries(readCsv(join(MEMORY, 'Roto & blow molding/roto_blow_molding_wage_grade_associations.csv')).rows
  .filter((g) => CLASS[g['Process Name']]).map((g) => [g['Process Name'], g['Wage Grade Name']]));
for (const [process, grade] of Object.entries(grades)) if (INDIA_LABOUR[grade] == null) throw new Error(`${process}: no India rate for ${grade}`);

const num = (v) => { const n = Number(String(v).replace(/[$,\s]/g, '')); return Number.isFinite(n) ? Math.round(n * 100) / 100 : 0; };
const q = (s) => `$str$${s}$str$`;
const india = readCsv(join(MEMORY, 'Countries data/India_XML_Data_.csv')).rows.filter((r) => r['Commodity'] === 'Roto & Blow Molding').map((r) => {
  const process = r['Machine Type'];
  const cls = CLASS[process];
  if (!cls) throw new Error(`no machine class for ${process}`);
  return { cls, name: r['name'], process, grade: grades[process], labour: INDIA_LABOUR[grades[process]], direct: num(r['customWorkCenterDirectOverheadRate']), indirect: num(r['customWorkCenterIndirectOverheadRate']) };
}).sort((a, b) => (a.cls + a.name).localeCompare(b.cls + b.name));
const byProcess = {};
for (const r of india) byProcess[r.process] = (byProcess[r.process] ?? 0) + 1;

const sql = `-- ============================================================================
-- Migration 1106: Roto & Blow Molding machines at India rates
-- ============================================================================
-- Generated by scripts/generate-roto-blow-machines-migration.js; re-run it and diff instead of editing.
--
-- Migration 862 seeded the ${india.length} Roto & Blow Molding machines for the USA only, so a blow or roto molded part priced in India had no machine.
--
-- India twins. Source: memory/Countries data/India_XML_Data_.csv, commodity "Roto & Blow Molding": each machine's direct and indirect overhead
-- rate (USD/hr, rounded to cents). Labour: the India rate of the process's wage grade (memory/Roto & blow molding wage grade associations:
-- Extrusion Blow Mold and Rotational Mold 4 - Plastic, Grind, Router and Saw 2 - Plastic), written to usd_labor_rate_per_hr AND usd_lhr_total
-- (the column the machine selector reads):
--   2 - Plastic  1.57 USD/hr, the rate the India rows of that grade carry.
--   4 - Plastic  1.96 USD/hr. No India row carries this grade: interpolated between the India 3 - Plastic (1.65) and 5 - Plastic (2.15) at the
--                point the USA 4 - Plastic rate (41.80) lies between the USA 3 and 5 (35.12, 45.81): 62.5 % of the way.
-- ${india.length} machines, each matched by machine class and exact name to its USA row:
${Object.entries(byProcess).sort().map(([p, n]) => `--   ${p.padEnd(22)}${n} machine(s)`).join('\n')}
--
-- Idempotent: an India row already present for its class and name is skipped.
-- Verify: SELECT location, machine_class, count(*) FROM mhr_records WHERE machine_class LIKE 'roto_blow_molding_%' GROUP BY 1, 2 ORDER BY 1, 2;
--   -- expect USA ${india.length} rows (5 classes), India ${india.length} rows (5 classes).
-- ============================================================================

DO $roto_blow_machines$
DECLARE
  cols text; sel text; r record; usa_id uuid; n integer := 0; missing text[] := '{}';
BEGIN
  SELECT
    string_agg(quote_ident(c.column_name), ', ' ORDER BY c.ordinal_position),
    string_agg(
      CASE c.column_name
        WHEN 'location'                                THEN '$5'
        WHEN 'country_code'                            THEN '$6'
        WHEN 'direct_overhead_rate'                    THEN '$2'
        WHEN 'indirect_overhead_rate'                  THEN '$3'
        WHEN 'benchmark_direct_overhead_rate_usd_hr'   THEN '$2'
        WHEN 'benchmark_indirect_overhead_rate_usd_hr' THEN '$3'
        WHEN 'total_machine_hour_rate'                 THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'mhr_usd_per_hour'                        THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'usd_labor_rate_per_hr'                   THEN '$4'
        WHEN 'usd_lhr_total'                           THEN '$4'
        WHEN 'benchmark_labor_rate_usd_hr'             THEN '$4'
        WHEN 'benchmark_source_key'                    THEN '$7'
        WHEN 'id'                                      THEN 'gen_random_uuid()'
        WHEN 'created_at'                              THEN 'now()'
        WHEN 'updated_at'                              THEN 'now()'
        ELSE 'usa_row.' || quote_ident(c.column_name)
      END, ', ' ORDER BY c.ordinal_position
    )
  INTO cols, sel
  FROM information_schema.columns c
  WHERE c.table_schema = 'public' AND c.table_name = 'mhr_records' AND c.is_generated = 'NEVER';

  -- (machine class, machine name, labour, direct, indirect, source key)
  FOR r IN SELECT * FROM (VALUES
${india.map((t) => `  (${q(t.cls)}, ${q(t.name)}, ${t.labour}, ${t.direct}, ${t.indirect}, ${q(`${t.process}:${t.name}:India`)})`).join(',\n')}
  ) AS v(machine_class, machine_name, labor, direct, indirect, source_key)
  LOOP
    SELECT id INTO usa_id FROM mhr_records
    WHERE location = 'USA' AND machine_class = r.machine_class AND machine_name = r.machine_name
    LIMIT 1;
    IF usa_id IS NULL THEN
      missing := array_append(missing, r.machine_class || ':' || r.machine_name);
      CONTINUE;
    END IF;
    IF EXISTS (SELECT 1 FROM mhr_records m WHERE m.location = 'India' AND m.machine_class = r.machine_class AND m.machine_name = r.machine_name) THEN
      CONTINUE;
    END IF;
    EXECUTE format('INSERT INTO mhr_records (%s) SELECT %s FROM mhr_records usa_row WHERE usa_row.id = $1', cols, sel)
      USING usa_id, r.direct, r.indirect, r.labor, 'India', 'IN', r.source_key;
    n := n + 1;
  END LOOP;

  RAISE NOTICE 'Roto & Blow Molding India rows inserted: %', n;
  IF array_length(missing, 1) > 0 THEN
    RAISE EXCEPTION 'Roto & Blow Molding machines with no USA row (migration 862): %', missing;
  END IF;
END $roto_blow_machines$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${india.length} India twins)`);
