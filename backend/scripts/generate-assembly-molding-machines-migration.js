/**
 * Writes migration 1079 (the Assembly Molding machines at India rates) from memory/Countries data:
 *   node scripts/generate-assembly-molding-machines-migration.js
 * Each India row is its USA twin (migration 862, same machine class and exact name) with the India export's overhead rates and the India rate
 * of its process's wage grade (memory/Assembly molding/wage_grade_associations.csv).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1079_assembly_molding_machines_india.sql');

// The machine class migration 862 gave each Assembly Molding process.
const CLASS = {
  'Insert Injection Molding': 'assembly_molding_insert_injection_molding',
  'Insert Pick and Place': 'assembly_molding_insert_pick_and_place',
};
// The India labour rate of each wage grade (USD/hr): the value every India row of that grade already carries in HR Rates
// (SELECT wage_grade, usd_labor_rate_per_hr FROM mhr_records WHERE location = 'India').
const INDIA_GRADE_RATE = { '3 - Plastic': 1.65, '2 - Metal': 1.65 };
// The India export spells two machines differently from the USA machine file: the twin takes the USA row's exact name.
const INDIA_NAME_TO_USA = { 'Magna V50 32 - 132.3ST': 'Magna V50 32 - 132.3 ST', 'Espon Flexion N2 - 780mm': 'Epson Flexion N2 - 780mm' };

const grades = Object.fromEntries(readCsv(join(MEMORY, 'Assembly molding/wage_grade_associations.csv')).rows
  .map((r) => [String(r['Process Name'] ?? r['﻿Process Name']).replace(/^﻿/, ''), r['Wage Grade Name']]));
const num = (v) => { const n = Number(String(v ?? '').replace(/[$,\s]/g, '')); return Number.isFinite(n) ? Math.round(n * 100) / 100 : 0; };
const q = (s) => `$str$${s}$str$`;

const india = readCsv(join(MEMORY, 'Countries data/India_XML_Data_.csv')).rows
  .filter((r) => r['Commodity'] === 'Assembly Molding')
  .map((r) => ({ ...r, name: INDIA_NAME_TO_USA[r['name']] ?? r['name'] }));
const byProcess = {};
const values = india.map((r) => {
  const process = r['Machine Type'];
  const cls = CLASS[process];
  if (!cls) throw new Error(`no machine class for ${process}`);
  const labour = INDIA_GRADE_RATE[grades[process]];
  if (labour == null) throw new Error(`no India rate for wage grade ${grades[process]} (${process})`);
  byProcess[process] = (byProcess[process] ?? 0) + 1;
  return { cls, name: r['name'], labour, direct: num(r['customWorkCenterDirectOverheadRate']), indirect: num(r['customWorkCenterIndirectOverheadRate']), key: `${process}:${r['name']}:India` };
}).sort((a, b) => (a.cls + a.name).localeCompare(b.cls + b.name));

const sql = `-- ============================================================================
-- Migration 1079: the Assembly Molding machines at India rates
-- ============================================================================
-- Generated by scripts/generate-assembly-molding-machines-migration.js; re-run it and diff instead of editing.
--
-- Migration 862 seeded the Assembly Molding machines (memory/Assembly molding/Machines) for the USA only, so an insert-molded part priced in
-- India had no press and no insert loader.
--
-- India: memory/Countries data/India_XML_Data_.csv, commodity "Assembly Molding" (${india.length} machines): each machine's direct and indirect
-- overhead rate (USD/hr, rounded to cents) on its USA twin (same class, exact name; the export spells two names differently:
-- ${Object.entries(INDIA_NAME_TO_USA).map(([a, b]) => `"${a}" is "${b}"`).join(', ')}). Labour: the India rate of the process's wage grade
-- (memory/Assembly molding/wage_grade_associations.csv: Insert Injection Molding 3 - Plastic, Insert Pick and Place 2 - Metal), the value the
-- India rows of that grade already carry (1.65 USD/hr each), written to usd_labor_rate_per_hr AND usd_lhr_total (the column the machine
-- selector reads; migration 1061).
${Object.entries(byProcess).sort().map(([p, n]) => `--   ${p.padEnd(26)}${n} machine(s)`).join('\n')}
--
-- Idempotent: a row already present for a location + machine_class + machine_name is skipped.
-- Verify: SELECT location, machine_class, count(*) FROM mhr_records WHERE machine_class LIKE 'assembly_molding%' GROUP BY 1, 2 ORDER BY 1, 2;
-- ============================================================================

DO $assembly_molding_machines$
DECLARE
  cols text; sel text; r record; src_id uuid; n integer := 0; missing text[] := '{}';
BEGIN
  SELECT
    string_agg(quote_ident(c.column_name), ', ' ORDER BY c.ordinal_position),
    string_agg(
      CASE c.column_name
        WHEN 'location'                                THEN '''India'''
        WHEN 'country_code'                            THEN '''IN'''
        WHEN 'direct_overhead_rate'                    THEN '$2'
        WHEN 'indirect_overhead_rate'                  THEN '$3'
        WHEN 'benchmark_direct_overhead_rate_usd_hr'   THEN '$2'
        WHEN 'benchmark_indirect_overhead_rate_usd_hr' THEN '$3'
        WHEN 'total_machine_hour_rate'                 THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'mhr_usd_per_hour'                        THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'usd_labor_rate_per_hr'                   THEN '$4'
        WHEN 'usd_lhr_total'                           THEN '$4'
        WHEN 'benchmark_labor_rate_usd_hr'             THEN '$4'
        WHEN 'benchmark_source_key'                    THEN '$5'
        WHEN 'id'                                      THEN 'gen_random_uuid()'
        WHEN 'created_at'                              THEN 'now()'
        WHEN 'updated_at'                              THEN 'now()'
        ELSE 'src.' || quote_ident(c.column_name)
      END, ', ' ORDER BY c.ordinal_position
    )
  INTO cols, sel
  FROM information_schema.columns c
  WHERE c.table_schema = 'public' AND c.table_name = 'mhr_records' AND c.is_generated = 'NEVER';

  -- (class, name, labour, direct, indirect, source key)
  FOR r IN SELECT * FROM (VALUES
${values.map((v) => `  (${q(v.cls)}, ${q(v.name)}, ${v.labour}, ${v.direct}, ${v.indirect}, ${q(v.key)})`).join(',\n')}
  ) AS v(machine_class, machine_name, labor, direct, indirect, source_key)
  LOOP
    SELECT id INTO src_id FROM mhr_records WHERE location = 'USA' AND machine_class = r.machine_class AND machine_name = r.machine_name LIMIT 1;
    IF src_id IS NULL THEN
      missing := array_append(missing, r.machine_class || ':' || r.machine_name);
      CONTINUE;
    END IF;
    IF EXISTS (SELECT 1 FROM mhr_records m WHERE m.location = 'India' AND m.machine_class = r.machine_class AND m.machine_name = r.machine_name) THEN
      CONTINUE;
    END IF;
    EXECUTE format('INSERT INTO mhr_records (%s) SELECT %s FROM mhr_records src WHERE src.id = $1', cols, sel)
      USING src_id, r.direct, r.indirect, r.labor, r.source_key;
    n := n + 1;
  END LOOP;

  RAISE NOTICE 'Assembly Molding India rows inserted: %', n;
  IF array_length(missing, 1) > 0 THEN
    RAISE NOTICE 'Assembly Molding rows with no USA twin (not inserted): %', missing;
  END IF;
END $assembly_molding_machines$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${india.length} India rows)`);
