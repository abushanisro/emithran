#!/usr/bin/env node
/**
 * Writes migration 1102 (the Powder Metal powders: their density, and the process's link to them) from
 * memory/Powder metal/Raw material/raw_materials.csv:
 *   node scripts/generate-powder-metal-materials-migration.js
 * Re-run and diff instead of editing the migration.
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv, sqlStr, sqlNum } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const SOURCE = 'Powder metal/Raw material/raw_materials.csv';
const OUT = join(__dirname, '../migrations/1102_powder_metal_materials.sql');
const GROUP = 'Powder Metal';
const COLUMN = 'Green Density (kg / m^3)';

const powders = readCsv(join(MEMORY, SOURCE)).rows.map((r) => {
  const density = Number(r[COLUMN]);
  if (!r['Name'] || !(density > 0)) throw new Error(`${SOURCE}: a powder with no name or ${COLUMN}: ${JSON.stringify(r)}`);
  return { name: String(r['Name']), density };
});
if (powders.length !== 7) throw new Error(`expected the 7 powders of ${SOURCE}, found ${powders.length}`);

const sql = `-- ============================================================================
-- Migration 1102: the Powder Metal powders -- their density, and the process's link to them
-- ============================================================================
-- Generated by scripts/generate-powder-metal-materials-migration.js; re-run it and diff instead of editing.
--
-- 1. Density: migration 855 moved the ${powders.length} powders of memory/${SOURCE} into raw_materials (material group '${GROUP}') with
--    no density (density_kg_m3 and density were left empty; the green density went to raw_material_properties only, migration 863). Every
--    material lookup outside the powder metal route keeps only rows with a density, so a powder was "not found in raw_materials": its
--    material cost and weight were 0, and the closest-material choice for a part whose grade is not a powder fell back to the first name.
--    A pressed part weighs its volume at the density it is pressed to: each powder's Green Density (kg/m³), the density the powder metal
--    route charges its mass at; density is the same in g/cm³. Written only where empty.
--
-- 2. The material picker: no process_material_groups row linked ${GROUP} to its powders, so the picker of a powder metal part listed the
--    whole database, and a grade shared with another group (the Ferrous & Non-Ferrous "Generic F-0005") was not resolved to the powder.
--    The process takes its own group, as migration 1090 did for Bar and Tube Fabrication.
--
-- Idempotent. Verify:
--   SELECT name, density_kg_m3, density FROM raw_materials WHERE material_group = '${GROUP}' ORDER BY name;
--   SELECT material_group FROM process_material_groups WHERE process_group = '${GROUP}';   -- ${GROUP}
-- ============================================================================

UPDATE raw_materials rm SET
  density_kg_m3 = COALESCE(rm.density_kg_m3, v.green_density),
  density = COALESCE(rm.density, v.green_density / 1000),
  updated_at = now()
FROM (VALUES
${powders.map((p) => `  (${sqlStr(p.name)}, ${sqlNum(p.density)}::numeric)`).join(',\n')}
) AS v(name, green_density)
WHERE rm.material_group = ${sqlStr(GROUP)} AND rm.name = v.name AND (rm.density_kg_m3 IS NULL OR rm.density IS NULL);

INSERT INTO process_material_groups (process_group, material_group) VALUES (${sqlStr(GROUP)}, ${sqlStr(GROUP)})
ON CONFLICT (process_group, material_group) DO NOTHING;

DO $powder_metal_materials_check$
DECLARE bare text[];
BEGIN
  SELECT array_agg(name ORDER BY name) INTO bare FROM raw_materials
   WHERE material_group = ${sqlStr(GROUP)} AND NOT (COALESCE(density_kg_m3, 0) > 0 AND COALESCE(density, 0) > 0);
  IF bare IS NOT NULL THEN RAISE EXCEPTION 'Powder Metal materials still without a density: %', bare; END IF;
END $powder_metal_materials_check$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${powders.length} powders)`);
