/**
 * Writes migration 1096 (the Machining machines' fractional crews) from memory/:
 *   node scripts/generate-machining-crews-migration.js
 *
 * mhr_records.operators was smallint when the Machining machines were seeded (migrations 738 and 829), so a crew of 0.25 (one operator
 * tending four multi-spindles) was stored as 0 and 0.5 as 1. Migration 971 made the column numeric(5,2) but changed no value, and its
 * restage script corrected the plastic presses only. Every machine of memory/machining/machine whose crew is a fraction is written here,
 * by name, to both locations' Machining rows: the India export (memory/Countries data/India_XML_Data_.csv) states the same crews.
 */
const { readdirSync, writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const DIR = join(__dirname, '../../memory/machining/machine');
const OUT = join(__dirname, '../migrations/1096_machining_fractional_crews.sql');
/** The machine files name their crew and their machine in one of two spellings each. */
const CREW = ['accounting.number_of_operators', 'accounting.numberOfOperators'];
const NAME = ['name', 'primary_id.name'];

const q = (s) => `$str$${s}$str$`;
const crews = readdirSync(DIR).filter((f) => f.endsWith('.csv')).sort().flatMap((file) => {
  const { columns, rows } = readCsv(join(DIR, file));
  const crew = CREW.find((c) => columns.includes(c));
  const name = NAME.find((c) => columns.includes(c));
  if (!crew) return [];
  if (!name) throw new Error(`${file}: a crew column but no machine name column`);
  return rows
    .map((r) => ({ file, name: String(r[name]).trim(), operators: Number(r[crew]) }))
    .filter((m) => Number.isFinite(m.operators) && !Number.isInteger(m.operators));
}).sort((a, b) => a.name.localeCompare(b.name));

const names = crews.map((m) => m.name);
const twice = names.filter((n, i) => names.indexOf(n) !== i);
if (twice.length) throw new Error(`a machine name is in more than one file: ${twice.join(', ')}`);
if (crews.length === 0) throw new Error('no fractional crew in memory/machining/machine: nothing to write');

const sql = `-- ============================================================================
-- Migration 1096: the Machining machines' fractional crews
-- ============================================================================
-- Generated by scripts/generate-machining-crews-migration.js; re-run it and diff instead of editing.
--
-- mhr_records.operators was smallint when the Machining machines were seeded (migrations 738 and 829): a crew of 0.25 (one operator tending
-- four CNC multi-spindles) was stored as 0, and 0.5 (one operator for two machines) as 1. Migration 971 made the column numeric(5,2) but
-- changed no value, and its restage script corrected the plastic presses only. So no labour was charged on a multi-spindle, and twice the
-- source's on a twin-spindle turning center and on the automated deburr cell.
--
-- Every machine of memory/machining/machine whose crew is a fraction, by name, on both locations' Machining rows (the India export,
-- memory/Countries data/India_XML_Data_.csv, states the same crews):
${crews.map((m) => `--   ${String(m.operators).padEnd(5)} ${m.name} (${m.file})`).join('\n')}
--
-- Only operators is written. Idempotent: the same values are re-set.
-- Verify: SELECT machine_name, location, operators FROM mhr_records WHERE process_group = 'Machining' AND operators <> round(operators) ORDER BY 1, 2;
-- ============================================================================

UPDATE mhr_records m SET operators = v.operators, updated_at = now()
FROM (VALUES
${crews.map((m) => `  (${q(m.name)}, ${m.operators})`).join(',\n')}
) AS v(machine_name, operators)
WHERE m.process_group = 'Machining' AND m.machine_name = v.machine_name AND m.operators IS DISTINCT FROM v.operators;

DO $crew_check$
DECLARE wrong text[];
BEGIN
  SELECT array_agg(m.location || ': ' || m.machine_name || ' ' || COALESCE(m.operators::text, 'null') ORDER BY m.location, m.machine_name) INTO wrong
    FROM mhr_records m
    JOIN (VALUES
${crews.map((m) => `      (${q(m.name)}, ${m.operators})`).join(',\n')}
    ) AS v(machine_name, operators) ON m.machine_name = v.machine_name
   WHERE m.process_group = 'Machining' AND m.operators IS DISTINCT FROM v.operators;
  IF wrong IS NOT NULL THEN RAISE EXCEPTION 'Machining machines whose crew still differs from memory/machining/machine: %', wrong; END IF;
END $crew_check$;

NOTIFY pgrst, 'reload schema';
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${crews.length} machines)`);
