/**
 * Writes migration 1090 (Bar and Tube Fabrication: the Circular Saw catalog rows' machine class, and the materials' strengths and extrusion exit
 * speeds) from memory/Bar and tube fab/Raw material/materials.csv:
 *   node scripts/generate-bar-tube-catalog-materials-migration.js
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1090_bar_tube_catalog_and_material_properties.sql');
const GROUP = 'Bar and Tube Fabrication';

const q = (s) => `$str$${s}$str$`;
const n = (v) => { const x = Number(String(v ?? '').trim()); return String(v ?? '').trim() !== '' && Number.isFinite(x) && x > 0 ? x : null; };
const sqlNum = (v) => (v == null ? 'NULL::numeric' : String(v));
const rows = readCsv(join(MEMORY, 'Bar and tube fab/Raw material/materials.csv')).rows.map((r) => ({
  name: r['Name'], shear: n(r['Shear Strength (MPa)']), yield: n(r['Tensile Yield Strength (MPa)']), uts: n(r['Ultimate Tensile Strength (MPa)']),
  exitMin: n(r['Minimum Extrusion Exit Speed (mm / s)']), exitMax: n(r['Maximum Extrusion Exit Speed (mm / s)']),
})).filter((r) => r.name);
const withExit = rows.filter((r) => r.exitMin != null && r.exitMax != null).length;

const sql = `-- ============================================================================
-- Migration 1090: Bar and Tube Fabrication catalog (Circular Saw) and material properties
-- ============================================================================
-- Generated by scripts/generate-bar-tube-catalog-materials-migration.js; re-run it and diff instead of editing.
--
-- 1. Circular Saw: its process_taxonomy and process_calculator_mappings rows (migration 862) have no machine class, because no Circular Saw
--    machine existed; migration 1089 seeds them as bar_tube_fab_circular_saw. A catalog row with no machine class cannot be active
--    (chk_machine_class_required), so the Circular Saw calculator of migration 1091 could not be opened. Set only where it is NULL.
--
-- 2. The ${rows.length} Bar and Tube materials (migration 855) carry no strengths: the promotion kept the cost and the physical columns but not
--    memory/Bar and tube fab/Raw material/materials.csv's Shear Strength, Tensile Yield Strength and Ultimate Tensile Strength. The bar and tube
--    engine needs them: roll bending switches to several passes above referenceTensileStrength (the material's UTS), bending tooling and the
--    bend brake's capacity read the yield, and the press force of punching and shearing reads the shear strength. Written only where empty.
--
-- 3. Extrusion exit speeds: the aluminium extrusion route runs the press at the material's exit speed (memory materials.csv Minimum and
--    Maximum Extrusion Exit Speed, mm/s; ${withExit} materials have them). raw_materials has no column for them: two are added and filled.
--
-- 4. The material picker: no process_material_groups row linked ${GROUP} to its materials (material_group '${GROUP}', migration
--    855), so the picker of a bar or tube part listed the whole database. The process takes its own group.
--
-- Verify:
--   SELECT material_group FROM process_material_groups WHERE process_group = '${GROUP}';   -- ${GROUP}
--   SELECT count(*) FILTER (WHERE uts_mpa IS NOT NULL), count(*) FILTER (WHERE extrusion_exit_speed_max_mm_s IS NOT NULL)
--   FROM raw_materials WHERE material_group = '${GROUP}';   -- expect ${rows.length}, ${withExit}
--   SELECT machine_class FROM process_taxonomy WHERE process_group = '${GROUP}' AND process_name = 'Circular Saw';   -- bar_tube_fab_circular_saw
-- ============================================================================

UPDATE process_taxonomy SET machine_class = 'bar_tube_fab_circular_saw'
WHERE process_group = '${GROUP}' AND process_name = 'Circular Saw' AND machine_class IS NULL;

UPDATE process_calculator_mappings SET machine_class = 'bar_tube_fab_circular_saw', updated_at = now()
WHERE process_group = '${GROUP}' AND operation = 'Circular Saw' AND machine_class IS NULL;

ALTER TABLE raw_materials ADD COLUMN IF NOT EXISTS extrusion_exit_speed_min_mm_s numeric;
ALTER TABLE raw_materials ADD COLUMN IF NOT EXISTS extrusion_exit_speed_max_mm_s numeric;
COMMENT ON COLUMN raw_materials.extrusion_exit_speed_min_mm_s IS 'Slowest exit speed the alloy is extruded at, mm/s (memory/Bar and tube fab materials.csv).';
COMMENT ON COLUMN raw_materials.extrusion_exit_speed_max_mm_s IS 'Fastest exit speed the alloy is extruded at, mm/s (memory/Bar and tube fab materials.csv).';

UPDATE raw_materials rm SET
  shear_strength_mpa = COALESCE(rm.shear_strength_mpa, v.shear),
  yield_strength_mpa = COALESCE(rm.yield_strength_mpa, v.yield_mpa),
  uts_mpa = COALESCE(rm.uts_mpa, v.uts),
  extrusion_exit_speed_min_mm_s = COALESCE(rm.extrusion_exit_speed_min_mm_s, v.exit_min),
  extrusion_exit_speed_max_mm_s = COALESCE(rm.extrusion_exit_speed_max_mm_s, v.exit_max),
  updated_at = now()
FROM (VALUES
${rows.map((r) => `  (${q(r.name)}, ${sqlNum(r.shear)}, ${sqlNum(r.yield)}, ${sqlNum(r.uts)}, ${sqlNum(r.exitMin)}, ${sqlNum(r.exitMax)})`).join(',\n')}
) AS v(name, shear, yield_mpa, uts, exit_min, exit_max)
WHERE rm.material_group = '${GROUP}' AND (rm.name = v.name OR rm.name = v.name || ' (${GROUP})');

INSERT INTO process_material_groups (process_group, material_group) VALUES ('${GROUP}', '${GROUP}')
ON CONFLICT (process_group, material_group) DO NOTHING;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} materials, ${withExit} with exit speeds)`);
