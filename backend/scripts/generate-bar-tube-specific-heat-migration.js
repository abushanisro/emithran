/**
 * Writes migration 1092 (Bar and Tube Fabrication: the materials' specific heat) from memory/Bar and tube fab/Raw material/materials.csv:
 *   node scripts/generate-bar-tube-specific-heat-migration.js
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1092_bar_tube_material_specific_heat.sql');
const GROUP = 'Bar and Tube Fabrication';

const q = (s) => `$str$${s}$str$`;
const n = (v) => { const x = Number(String(v ?? '').trim()); return String(v ?? '').trim() !== '' && Number.isFinite(x) && x > 0 ? x : null; };
const rows = readCsv(join(MEMORY, 'Bar and tube fab/Raw material/materials.csv')).rows
  .map((r) => ({ name: r['Name'], heat: n(r['Specific Heat RT (J / kg * K)']) }))
  .filter((r) => r.name && r.heat != null);

const sql = `-- ============================================================================
-- Migration 1092: Bar and Tube Fabrication materials' specific heat
-- ============================================================================
-- Generated by scripts/generate-bar-tube-specific-heat-migration.js; re-run it and diff instead of editing.
--
-- The ${rows.length} Bar and Tube materials (migration 855) carry no specific heat: the promotion dropped memory/Bar and tube fab/Raw material/
-- materials.csv's Specific Heat RT column, and migration 1090 filled the strengths and exit speeds but not it. The extrusion route heats each
-- billet to its extrusion temperature (calculator Bar and Tube - Billet preheat, migration 1091: mass x specific heat x temperature rise), so
-- without it no extruded profile could be costed. Written only where empty.
--
-- Verify:
--   SELECT count(*) FILTER (WHERE specific_heat_rt_j_kg_k IS NOT NULL) FROM raw_materials WHERE material_group = '${GROUP}';   -- expect ${rows.length}
-- ============================================================================

UPDATE raw_materials rm SET
  specific_heat_rt_j_kg_k = v.heat,
  updated_at = now()
FROM (VALUES
${rows.map((r) => `  (${q(r.name)}, ${r.heat})`).join(',\n')}
) AS v(name, heat)
WHERE rm.material_group = '${GROUP}' AND rm.specific_heat_rt_j_kg_k IS NULL AND (rm.name = v.name OR rm.name = v.name || ' (${GROUP})');

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} materials)`);
