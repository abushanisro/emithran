/**
 * Writes migration 1093 (the multi-spindle machines' limits and slide layout, the inputs Multi-Spindle Machining sizes and times a part with)
 * from memory/:
 *   node scripts/generate-multi-spindle-machines-migration.js
 *
 * The 15 Simultaneous Turning machines (memory/Machining/machine/simultaneous_turning_usa.csv: CNC multi-spindles with 6 or 8 spindles and
 * twin-spindle turning centers) were seeded for USA (migration 738) and India (829) with their rates, setup and index times (788) only. Their
 * limits and slide layout stayed in the CSV, so no part could be checked against a machine's bar capacity or length, and no station plan
 * could be laid out on its spindles. Written by machine name to both locations' rows: the typed max_diameter_mm / max_length_mm the machine
 * selector reads (as migration 755 did for the lathes), and the rest as specs keys.
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const SOURCE = 'machining/machine/simultaneous_turning_usa.csv';
const OUT = join(__dirname, '../migrations/1093_multi_spindle_machine_limits.sql');
const CLASS = 'simultaneous_turning';

const q = (s) => `$str$${s}$str$`;
const num = (v) => {
  const n = Number(String(v ?? '').trim());
  if (String(v ?? '').trim() === '' || !Number.isFinite(n)) throw new Error(`not a number: "${v}"`);
  return n;
};
/** "1, 1, 2, 2" -> [1, 1, 2, 2]: each listed spindle has one slide of the kind (a spindle listed twice has two). */
const spindles = (v) => {
  const list = String(v ?? '').split(',').map((s) => s.trim()).filter(Boolean).map(num);
  if (list.length === 0) throw new Error(`no spindles in "${v}"`);
  return list;
};
const bool = (v) => {
  const s = String(v ?? '').trim().toLowerCase();
  if (s !== 'true' && s !== 'false') throw new Error(`not a boolean: "${v}"`);
  return s === 'true';
};

const machines = readCsv(join(MEMORY, SOURCE)).rows.map((r) => {
  const m = {
    name: String(r['name']).trim(),
    processType: String(r['process_type']).trim(),
    spindleCount: num(r['slide_configuration.number_spindles']),
    od: spindles(r['slide_configuration.spindles_with_od_slide']),
    end: spindles(r['slide_configuration.spindles_with_end_slide']),
    live: spindles(r['slide_configuration.spindles_with_live_tooling']),
    back: spindles(r['slide_configuration.back_work_spindles']),
    maxDiameterMm: num(r['limits.max_diameter_mm']),
    maxLengthMm: num(r['limits.max_length_mm']),
    spindleSpeedRpm: num(r['limits.spindle_speed_rpm']),
    spindlePowerKw: num(r['limits.spindle_power_kW']),
    travelZMm: num(r['limits.travel_z_axis_mm']),
    maxMillToolDiameterMm: num(r['limits.max_mill_tool_diameter_mm']),
    liveToolingSpeedRpm: num(r['rates.live_tooling_spindle_speed_rpm']),
    rapidTraverseMmPerMin: num(r['rates.rapid_traverse_rate_mm_per_min']),
    basePartSetupTimeHr: num(r['time.base_part_setup_time_hr']),
    partEjectTimeS: num(r['time.part_eject_time_s']),
    toolPositioningTimeS: num(r['time.tool_positioning_time_s']),
    dullToolReplaceTimeS: num(r['time.time_to_replace_dull_tool_s']),
    spottingTimeS: num(r['time.spotting_time_s']),
    countersinkingTimeS: num(r['time.countersinking_time_s']),
    approachDepartMm: num(r['other.approach_depart_distance_mm']),
    canGunDrill: bool(r['other.can_gun_drill']),
  };
  // A slide on a spindle the machine does not have, or back work on none of them, is a broken row: stop rather than write it.
  const outside = [...m.od, ...m.end, ...m.live, ...m.back].filter((s) => s < 1 || s > m.spindleCount);
  if (outside.length) throw new Error(`${m.name}: spindle(s) ${outside.join(', ')} outside 1..${m.spindleCount}`);
  return m;
}).sort((a, b) => a.name.localeCompare(b.name));

if (machines.length !== 15) throw new Error(`expected the 15 Simultaneous Turning machines, read ${machines.length}`);

const arr = (list) => `'${JSON.stringify(list)}'::jsonb`;
const row = (m) => `  (${[
  q(m.name), q(m.processType), m.maxDiameterMm, m.maxLengthMm, arr(m.od), arr(m.end), arr(m.live), arr(m.back),
  m.spindleSpeedRpm, m.spindlePowerKw, m.travelZMm, m.maxMillToolDiameterMm, m.liveToolingSpeedRpm, m.rapidTraverseMmPerMin,
  m.basePartSetupTimeHr, m.partEjectTimeS, m.toolPositioningTimeS, m.dullToolReplaceTimeS, m.spottingTimeS, m.countersinkingTimeS,
  m.approachDepartMm, m.canGunDrill,
].join(', ')})`;

const sql = `-- ============================================================================
-- Migration 1093: the multi-spindle machines' limits and slide layout
-- ============================================================================
-- Generated by scripts/generate-multi-spindle-machines-migration.js; re-run it and diff instead of editing.
--
-- The 15 Simultaneous Turning machines of memory/${SOURCE} (CNC multi-spindles with 6 or 8 spindles and twin-spindle
-- turning centers; HR Rates class ${CLASS}) were seeded for USA (migration 738) and India (829) with their rates, setup and index times
-- (788). Their limits and slide layout stayed in the CSV: max_diameter_mm and max_length_mm were empty (migration 755 filled them for the
-- lathes only), so the machine selector could not check a part's bar against any of them and chose the cheapest hourly rate; and no station
-- plan could be laid out, because which spindle carries which slide, and which spindles do the back work, was nowhere.
--
-- Written by machine name to both locations' rows (Multi-Spindle Machining, user decision 2026-11-20):
--   typed  max_diameter_mm, max_length_mm (limits.*, the bar capacity and the part length the machine takes)
--   specs  process_type; od_slide_spindles, end_slide_spindles, live_tooling_spindles, back_work_spindles (slide_configuration.*: a spindle
--          listed twice carries two slides of the kind, the twin turrets of a sub-spindle turning center); spindle_speed_rpm,
--          spindle_power_kw, travel_z_mm, max_mill_tool_diameter_mm, live_tooling_speed_rpm, rapid_traverse_mm_per_min (limits.*, rates.*);
--          base_part_setup_time_hr, part_eject_time_s, tool_positioning_time_s, dull_tool_replace_time_s, spotting_time_s,
--          countersinking_time_s (time.*); approach_depart_mm, can_gun_drill (other.*)
--
-- Idempotent: the same values are re-set.
-- Verify: SELECT location, count(*), count(max_diameter_mm), count(specs->'od_slide_spindles') FROM mhr_records
--           WHERE machine_class = '${CLASS}' GROUP BY 1 ORDER BY 1;
-- ============================================================================

UPDATE mhr_records m SET
  max_diameter_mm = v.max_diameter_mm,
  max_length_mm = v.max_length_mm,
  specs = COALESCE(m.specs, '{}'::jsonb) || jsonb_build_object(
    'process_type', v.process_type,
    'od_slide_spindles', v.od_slide_spindles, 'end_slide_spindles', v.end_slide_spindles,
    'live_tooling_spindles', v.live_tooling_spindles, 'back_work_spindles', v.back_work_spindles,
    'spindle_speed_rpm', v.spindle_speed_rpm, 'spindle_power_kw', v.spindle_power_kw, 'travel_z_mm', v.travel_z_mm,
    'max_mill_tool_diameter_mm', v.max_mill_tool_diameter_mm, 'live_tooling_speed_rpm', v.live_tooling_speed_rpm,
    'rapid_traverse_mm_per_min', v.rapid_traverse_mm_per_min, 'base_part_setup_time_hr', v.base_part_setup_time_hr,
    'part_eject_time_s', v.part_eject_time_s, 'tool_positioning_time_s', v.tool_positioning_time_s,
    'dull_tool_replace_time_s', v.dull_tool_replace_time_s, 'spotting_time_s', v.spotting_time_s,
    'countersinking_time_s', v.countersinking_time_s, 'approach_depart_mm', v.approach_depart_mm, 'can_gun_drill', v.can_gun_drill),
  updated_at = now()
FROM (VALUES
${machines.map(row).join(',\n')}
) AS v(machine_name, process_type, max_diameter_mm, max_length_mm, od_slide_spindles, end_slide_spindles, live_tooling_spindles,
       back_work_spindles, spindle_speed_rpm, spindle_power_kw, travel_z_mm, max_mill_tool_diameter_mm, live_tooling_speed_rpm,
       rapid_traverse_mm_per_min, base_part_setup_time_hr, part_eject_time_s, tool_positioning_time_s, dull_tool_replace_time_s,
       spotting_time_s, countersinking_time_s, approach_depart_mm, can_gun_drill)
WHERE m.machine_class = '${CLASS}' AND m.machine_name = v.machine_name;

DO $ms_check$
DECLARE bare text[];
BEGIN
  SELECT array_agg(location || ': ' || machine_name ORDER BY location, machine_name) INTO bare FROM mhr_records
   WHERE machine_class = '${CLASS}' AND (max_diameter_mm IS NULL OR max_length_mm IS NULL OR NOT specs ? 'od_slide_spindles');
  IF bare IS NOT NULL THEN RAISE EXCEPTION 'Multi-spindle machines still without limits or slide layout (not in memory/${SOURCE}): %', bare; END IF;
END $ms_check$;

NOTIFY pgrst, 'reload schema';
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${machines.length} machines)`);
