// Audit of the plastics data staged in memory/ (injection molding): consistency between the two material files, injection data per material, press
// sanity, which staged variables and lookup tables the backend reads, and housekeeping. Read-only; the rules are in src/test-tools/plastic-data-audit.ts.
//
//   ts-node scripts/plastic-data-audit.ts [--memory <dir>] [--detail <file.json>]
//
// Prints a Markdown report: counts and names only, safe to commit. memory/ is licensed data, so values go only to --detail, a file you keep local.
import * as fs from 'fs';
import * as path from 'path';

import { compareMaterialFiles, housekeeping, injectionGaps, parseCsv, pressFindings, unreadNames, type Row } from '../src/test-tools/plastic-data-audit';

const arg = (name: string): string | undefined => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const memory = path.resolve(arg('memory') ?? path.join(__dirname, '../../memory'));
const read = (rel: string): Row[] => parseCsv(fs.readFileSync(path.join(memory, rel), 'utf8'));

const walk = (dir: string): string[] =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));

const backendSrc = path.resolve(__dirname, '../src');
const codeText = walk(backendSrc)
  .filter((f) => f.endsWith('.ts') && !/[\\/](test|test-tools)[\\/]|\.spec\.ts$/.test(f))
  .map((f) => fs.readFileSync(f, 'utf8'))
  .join('\n');

const FINAL = 'Plastic Modeling/materials_final.csv';
const FULL = 'Assembly plastic molding/Raw Materials/raw_materials_full.csv';
const PRESSES = 'Plastic Modeling/machine/injection_molding_machines.csv';

const finalRows = read(FINAL);
const fullRows = read(FULL);
const presses = read(PRESSES);
const files = walk(path.join(memory, 'Plastic Modeling')).map((f) => path.relative(path.join(memory, 'Plastic Modeling'), f));

const materials = compareMaterialFiles(finalRows, fullRows);
const gaps = injectionGaps(finalRows);
const press = pressFindings(presses);
const variables = read('Plastic Modeling/variables/digital_factory_variables.csv').map((r) => r['variableName'] ?? '');
const lookupDir = path.join(memory, 'Plastic Modeling/lookup');
const lookups = fs.readdirSync(lookupDir).filter((f) => /__records\.csv$|\.csv$/.test(f) && !/__(fields|columns)\.csv$/.test(f)).map((f) => f.replace(/__records\.csv$|\.csv$/, ''));
const unreadVariables = unreadNames(variables, codeText);
const unreadLookups = unreadNames(lookups, codeText);
const house = housekeeping(files);

const byField = new Map<string, number>();
for (const d of materials.differences) byField.set(d.field, (byField.get(d.field) ?? 0) + 1);
const materialsWithDifference = new Set(materials.differences.map((d) => d.material));
const list = (xs: string[], max = 40) => (xs.length === 0 ? 'none' : xs.slice(0, max).map((x) => `\`${x}\``).join(', ') + (xs.length > max ? `, and ${xs.length - max} more` : ''));

const out: string[] = [];
out.push('# Plastic molding data audit (memory/)', '',
  'Generated by `backend/scripts/plastic-data-audit.ts`; rules in `backend/src/test-tools/plastic-data-audit.ts`. `memory/` is licensed data, so this report',
  'names rows and fields and gives counts, never values. Run the script with `--detail <file>` for the values.', '',
  '## 1. The two staged material files disagree', '',
  `\`${FINAL}\` (${finalRows.length} materials) against \`${FULL}\` (${fullRows.length}).`, '',
  `- Materials in both files with at least one differing value (0.5% tolerance): **${materialsWithDifference.size}**.`,
  ...[...byField.entries()].sort((a, b) => b[1] - a[1]).map(([f, n]) => `  - ${f}: ${n} materials`),
  `- Only in the first file: ${list(materials.onlyInFinal)}. Only in the second: ${list(materials.onlyInFull)}.`,
  '- Migration 861 filled USA prices from the first file. Which file is authoritative is a decision for the data owner; until then a price may differ by the file it came from.', '',
  '## 2. Injection-capable materials that lack what the engine reads', '',
  `Of ${finalRows.filter((r) => r['processCompatibility.canIM_SFM']?.toLowerCase() === 'true').length} materials flagged \`canIM_SFM\`, **${gaps.length}** lack at least one of injection pressure, flow length ratio, melt temperature, mold temperature, melt density (a zero temperature counts as missing).`,
  gaps.length ? `\n${list(gaps.map((g) => `${g.material} (${g.missing.join(', ')})`))}` : '', '',
  '## 3. Presses (injection_molding_machines.csv)', '',
  `${press.presses} presses. Price per kN of clamp more than 4x away from the file's median: ${list(press.findings.map((f) => f.press))}.`, '',
  'Blank columns the injection engine reads:', '',
  ...Object.entries(press.blanks).map(([col, n]) => `- \`${col}\`: ${n} of ${press.presses}`), '',
  '## 4. What the backend reads', '',
  `- Staged Plastic Modeling variables: ${variables.length}; never named in non-test backend source: **${unreadVariables.length}**.`,
  `- Staged lookup tables: ${lookups.length}; never named in non-test backend source: **${unreadLookups.length}**: ${list(unreadLookups)}.`,
  '- "Never named" is a text search of `backend/src` (tests excluded), so a name built at run time would show here; each is a candidate to confirm, not a proven gap.', '',
  '## 5. Housekeeping', '',
  `- Download copies beside their original: ${list(house.copies)}.`,
  `- Numbered files with no original beside them: ${list(house.strayCopies)}.`,
  `- Files that look like another domain's data: ${list(house.notPlastics)}.`, '');
console.log(out.join('\n'));

const detail = arg('detail');
if (detail) {
  fs.writeFileSync(detail, JSON.stringify({ materialDifferences: materials.differences, injectionGaps: gaps, pressFindings: press.findings, pressBlanks: press.blanks, unreadVariables, unreadLookups, housekeeping: house }, null, 2));
}
