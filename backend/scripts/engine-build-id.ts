// Writes the identifier of the plastic cost engine's code (a hash of every runtime source file it reaches) to
// src/modules/bom-items/costing/plastic-molding/engine-build.generated.ts, or with --check compares it to the committed file.
//   npm run engine-build          regenerate (commit the result with the engine change)
//   npm run engine-build:check    fail if the committed file is out of date (the test suite also runs this check)
import * as fs from 'fs';
import * as path from 'path';
import { computeEngineBuild } from '../src/test-tools/engine-build-id';

export const ROOT_FILE = path.resolve(__dirname, '../src/modules/bom-items/costing/plastic-molding/process/cost-injection-molding-engine.ts');
export const GENERATED = path.resolve(__dirname, '../src/modules/bom-items/costing/plastic-molding/engine-build.generated.ts');
const REPO = path.resolve(__dirname, '..');

export function render(): string {
  const b = computeEngineBuild(ROOT_FILE, REPO);
  return `// GENERATED by \`npm run engine-build\` (scripts/engine-build-id.ts). Do not edit: a test fails when it is stale.
// The identifier of the plastic cost engine's code: a hash of ${b.files} source files (process/cost-injection-molding-engine.ts and every runtime file it
// imports). A saved calculation records it; a replay compares it with this one and says whether the same code is running.
export const PLASTIC_ENGINE_BUILD = { codeHash: '${b.codeHash}', files: ${b.files} } as const;
`;
}

if (require.main === module) {
  const next = render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(GENERATED) ? fs.readFileSync(GENERATED, 'utf8') : '';
    if (current !== next) {
      console.error('engine-build.generated.ts is out of date with the engine code.\nRegenerate it and commit it with your change:\n  cd backend && npm run engine-build');
      process.exit(1);
    }
    console.log('engine-build.generated.ts is up to date');
  } else {
    fs.writeFileSync(GENERATED, next);
    console.log(`wrote ${path.relative(REPO, GENERATED)}`);
  }
}
