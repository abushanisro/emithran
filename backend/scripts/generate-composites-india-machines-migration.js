/**
 * Writes migration 1063 (the composites machines at India rates) from memory/Countries data/India_XML_Data_.csv:
 *   node scripts/generate-composites-india-machines-migration.js
 * Each India row is its USA twin (migration 796, same machine class and exact name) with the India direct and indirect overhead rates of
 * the export and the India rate of its process's wage grade (memory/Composites/wage_grade_associations).
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1063_composites_india_machines.sql');

// The machine class migration 796 gave each composites process.
const CLASS = {
  'Autoclave Cure': 'autoclave_cure', 'Automated Fiber Placement': 'automated_fiber_placement', 'Automated Tape Layup': 'automated_tape_layup',
  'Bench Operation': 'composite_bench_operation', 'Hand Layup': 'hand_layup', 'Mold Preparation': 'mold_preparation', 'Tool Clean': 'tool_clean',
  'Ultrasonic Cut': 'composite_ultrasonic_cut',
};
// The India labour rate of each wage grade (USD/hr): the value every India row of that grade already carries in HR Rates
// (SELECT wage_grade, usd_labor_rate_per_hr FROM mhr_records WHERE location = 'India'), as migration 1049 used.
const INDIA_GRADE_RATE = { '3 - Metal': 1.73, '4 - Metal': 2.3, '5 - Metal': 2.75, '6 - Metal': 3.52 };

const grades = Object.fromEntries(readCsv(join(MEMORY, 'Composites/wage_grade_associations (6).csv')).rows.map((r) => [r['Process Name'], r['Wage Grade Name']]));
const india = readCsv(join(MEMORY, 'Countries data/India_XML_Data_.csv')).rows.filter((r) => r['Commodity'] === 'Composites');
const num = (v) => { const n = Number(v); return Number.isFinite(n) ? Math.round(n * 100) / 100 : 0; };
const q = (s) => `$str$${s}$str$`;
const rows = india.map((r) => {
  const process = r['Machine Type'];
  const cls = CLASS[process];
  const grade = grades[process];
  const labour = INDIA_GRADE_RATE[grade];
  if (!cls) throw new Error(`no machine class for ${process}`);
  if (labour == null) throw new Error(`no India rate for wage grade ${grade} (${process})`);
  return { cls, name: r['name'], labour, direct: num(r['customWorkCenterDirectOverheadRate']), indirect: num(r['customWorkCenterIndirectOverheadRate']), process };
}).sort((a, b) => (a.cls + a.name).localeCompare(b.cls + b.name));
const byProcess = {};
for (const r of rows) byProcess[r.process] = (byProcess[r.process] ?? 0) + 1;

const sql = `-- ============================================================================
-- Migration 1063: Composites machines, India rates (USA twin cloned at India rates)
-- ============================================================================
-- Generated by scripts/generate-composites-india-machines-migration.js; re-run it and diff instead of editing.
--
-- Migration 796 seeded the 87 composites machines for the USA only, so a composite part priced in India had no machine on any step.
--
-- Source: memory/Countries data/India_XML_Data_.csv, commodity "Composites": each machine's direct and indirect overhead rate
-- (USD/hr, rounded to cents). Labour: the India rate of the process's wage grade (memory/Composites/wage_grade_associations), the value
-- every India row of that grade already carries (3 - Metal 1.73, 4 - Metal 2.30, 5 - Metal 2.75, 6 - Metal 3.52 USD/hr), written to
-- usd_labor_rate_per_hr AND usd_lhr_total (the column the machine selector reads; migration 1061 had to repair the twins that kept the
-- USA value there). The USA hand layup cells have no overhead rates in their file; their India rows do, and carry them.
-- ${rows.length} machines, each matched by machine class and exact name to its USA row:
${Object.entries(byProcess).sort().map(([p, n]) => `--   ${p.padEnd(26)}${n} machine(s)`).join('\n')}
--
-- Idempotent: an India row already present for a machine_class + machine_name is skipped.
-- Verify: SELECT machine_class, count(*) FROM mhr_records WHERE process_group = 'Composites' AND location = 'India' GROUP BY 1 ORDER BY 1;
--   -- expect 8 classes, ${rows.length} rows.
-- ============================================================================

DO $india_composites$
DECLARE
  cols text; sel text; r record; usa_id uuid; n integer := 0; missing text[] := '{}';
BEGIN
  SELECT
    string_agg(quote_ident(c.column_name), ', ' ORDER BY c.ordinal_position),
    string_agg(
      CASE c.column_name
        WHEN 'location'                                THEN '''India'''
        WHEN 'country_code'                            THEN '''IN'''
        WHEN 'direct_overhead_rate'                    THEN '$2'
        WHEN 'indirect_overhead_rate'                  THEN '$3'
        WHEN 'benchmark_direct_overhead_rate_usd_hr'   THEN '$2'
        WHEN 'benchmark_indirect_overhead_rate_usd_hr' THEN '$3'
        WHEN 'total_machine_hour_rate'                 THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'mhr_usd_per_hour'                        THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'manual_mhr_value'                        THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'fully_burdened_local_per_hr'             THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'usd_labor_rate_per_hr'                   THEN '$4'
        WHEN 'usd_lhr_total'                           THEN '$4'
        WHEN 'benchmark_labor_rate_usd_hr'             THEN '$4'
        WHEN 'benchmark_source_key'                    THEN 'usa_row.benchmark_source_key || '':India'''
        WHEN 'id'                                      THEN 'gen_random_uuid()'
        WHEN 'created_at'                              THEN 'now()'
        WHEN 'updated_at'                              THEN 'now()'
        ELSE 'usa_row.' || quote_ident(c.column_name)
      END, ', ' ORDER BY c.ordinal_position
    )
  INTO cols, sel
  FROM information_schema.columns c
  WHERE c.table_schema = 'public' AND c.table_name = 'mhr_records' AND c.is_generated = 'NEVER';

  FOR r IN SELECT * FROM (VALUES
${rows.map((r) => `  (${q(r.cls)}, ${q(r.name)}, ${r.labour}, ${r.direct}, ${r.indirect})`).join(',\n')}
  ) AS v(machine_class, usa_name, labor, direct, indirect)
  LOOP
    SELECT id INTO usa_id FROM mhr_records
    WHERE process_group = 'Composites' AND location = 'USA' AND machine_class = r.machine_class AND machine_name = r.usa_name
    LIMIT 1;
    IF usa_id IS NULL THEN
      missing := array_append(missing, r.machine_class || ':' || r.usa_name);
      CONTINUE;
    END IF;
    IF EXISTS (SELECT 1 FROM mhr_records m WHERE m.location = 'India' AND m.machine_class = r.machine_class AND m.machine_name = r.usa_name) THEN
      CONTINUE;
    END IF;
    EXECUTE format(
      'INSERT INTO mhr_records (%s) SELECT %s FROM mhr_records usa_row WHERE usa_row.id = $1',
      cols, sel
    ) USING usa_id, r.direct, r.indirect, r.labor;
    n := n + 1;
  END LOOP;

  RAISE NOTICE 'Composites India rows inserted: %', n;
  IF array_length(missing, 1) > 0 THEN
    RAISE NOTICE 'Composites India rows with no USA row (not inserted): %', missing;
  END IF;
END $india_composites$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} machines)`);
