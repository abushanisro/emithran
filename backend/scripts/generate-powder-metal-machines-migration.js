#!/usr/bin/env node
/**
 * Writes migration 1101 (the Powder Metal machines: the crews memory gives them, and the India twins) from memory/Powder metal/Machines and
 * memory/Countries data/India_XML_Data_.csv:
 *   node scripts/generate-powder-metal-machines-migration.js
 * Re-run and diff instead of editing the migration.
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv, sqlStr, sqlNum, twinMachinesSql } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const DIR = 'Powder metal';
const EXPORT = 'Countries data/India_XML_Data_.csv';
const OUT = join(__dirname, '../migrations/1101_powder_metal_machines.sql');
const GROUP = 'Powder Metal';
const CLASS = { 'Compaction Pressing': 'powder_metal_compaction_pressing', 'Furnace Sintering': 'powder_metal_furnace_sintering' };
const FILE = { 'Compaction Pressing': 'machines_compaction_pressing.csv', 'Furnace Sintering': 'machines_furnace_sintering.csv' };
// The India labour rate of each wage grade (USD/hr): the rate the India rows of that grade carry in HR Rates (222 rows of 4 - Metal at 2.30),
// as migrations 1075 and 1098 took theirs.
const INDIA_GRADE_RATE = { '4 - Metal': 2.30 };

const num = (v) => (v == null || v === '' || !Number.isFinite(Number(v)) ? null : Number(v));
const cents = (v) => {
  const n = num(v);
  if (n == null) throw new Error(`not a rate: ${v}`);
  return Math.round(n * 100) / 100;
};

const grades = Object.fromEntries(readCsv(join(MEMORY, DIR, 'wage_grade_associations.csv')).rows.map((r) => [r['Process Name'], r['Wage Grade Name']]));

// Each USA machine's crew, as memory gives it (half an operator on the smaller presses, one and a half on the 36" belt).
const crews = [];
for (const [process, file] of Object.entries(FILE)) {
  for (const r of readCsv(join(MEMORY, DIR, 'Machines', file)).rows) {
    const operators = num(r['Number of Operators']);
    if (!(operators > 0)) throw new Error(`${process} ${r['Name']}: no crew in ${file}`);
    crews.push({ cls: CLASS[process], name: r['Name'], operators });
  }
}
if (crews.length !== 16) throw new Error(`expected the 16 Powder Metal machines, found ${crews.length}`);

// The India twins: each machine's overhead (USD/hr, to cents) from its row of the export, labour at the India rate of its process's grade.
const byProcess = {};
const twins = readCsv(join(MEMORY, EXPORT)).rows.filter((r) => r['Commodity'] === GROUP).map((r) => {
  const process = r['Machine Type'];
  const machineClass = CLASS[process];
  if (!machineClass) throw new Error(`no machine class for ${process}`);
  const labour = INDIA_GRADE_RATE[grades[process]];
  if (labour == null) throw new Error(`no India rate for wage grade ${grades[process]} (${process})`);
  if (!crews.some((c) => c.cls === machineClass && c.name === r['name'])) throw new Error(`${process} ${r['name']}: not a USA machine`);
  byProcess[process] = (byProcess[process] ?? 0) + 1;
  return {
    location: 'India', countryCode: 'IN', machineClass, machineName: r['name'], labour,
    direct: cents(r['customWorkCenterDirectOverheadRate']), indirect: cents(r['customWorkCenterIndirectOverheadRate']), sourceKey: `${process}:${r['name']}:India`,
  };
}).sort((a, b) => (a.machineClass + a.machineName).localeCompare(b.machineClass + b.machineName));
if (twins.length !== 16) throw new Error(`expected the 16 Powder Metal machines in ${EXPORT}, found ${twins.length}`);

const sql = `-- ============================================================================
-- Migration 1101: the Powder Metal machines -- the crews memory gives them, and India
-- ============================================================================
-- Generated by scripts/generate-powder-metal-machines-migration.js; re-run it and diff instead of editing.
--
-- Powder Metal had its 16 machines in HR Rates for the USA only, so a Powder Metal part in India was not costed ("HR Rates has no powder
-- metal machines for India"), and their crews were wrong:
--   * crews: memory gives the smaller presses half an operator and the 36" belt furnace one and a half; they were stored as 1 and 2 (rounded
--     up when the column held whole numbers; migration 971 widened it), so their labour was charged up to twice over. Set from
--     memory/${DIR}/Machines, before the India twins copy them.
--
-- India: memory/${EXPORT}, commodity "${GROUP}" (${twins.length} machines, the same as the USA files): each machine's direct and indirect
-- overhead (USD/hr, to cents) on its USA twin (same class, exact name). Labour: the India rate of the processes' wage grade
-- (memory/${DIR}/wage_grade_associations.csv: 4 - Metal), the rate the India rows of that grade carry in HR Rates, 2.30 USD/hr.
${Object.entries(byProcess).sort().map(([p, k]) => `--   ${p.padEnd(24)}${k} machine(s)`).join('\n')}
--
-- Idempotent. Verify:
--   SELECT location, machine_class, count(*), sum(operators) FROM mhr_records WHERE process_group = '${GROUP}' GROUP BY 1, 2 ORDER BY 1, 2;
-- ============================================================================

UPDATE mhr_records m
SET operators = v.operators, updated_at = now()
FROM (VALUES
${crews.map((c) => `  (${sqlStr(c.cls)}, ${sqlStr(c.name)}, ${sqlNum(c.operators)}::numeric)`).join(',\n')}
) AS v(machine_class, machine_name, operators)
WHERE m.process_group = ${sqlStr(GROUP)} AND m.location = 'USA' AND m.machine_class = v.machine_class AND m.machine_name = v.machine_name
  AND m.operators IS DISTINCT FROM v.operators;

${twinMachinesSql({ tag: 'powder_metal_machines', processGroup: GROUP, twins })}

DO $powder_metal_check$
DECLARE wrong text[]; n integer;
BEGIN
  SELECT array_agg(m.location || ': ' || m.machine_name || ' ' || m.operators ORDER BY m.location, m.machine_name) INTO wrong
  FROM mhr_records m JOIN (VALUES
${crews.map((c) => `    (${sqlStr(c.cls)}, ${sqlStr(c.name)}, ${sqlNum(c.operators)}::numeric)`).join(',\n')}
  ) AS v(machine_class, machine_name, operators) ON m.machine_class = v.machine_class AND m.machine_name = v.machine_name
  WHERE m.process_group = ${sqlStr(GROUP)} AND m.location IN ('USA', 'India') AND m.operators IS DISTINCT FROM v.operators;
  IF wrong IS NOT NULL THEN RAISE EXCEPTION 'Powder Metal machines whose crew is not memory''s: %', wrong; END IF;
  SELECT count(*) INTO n FROM mhr_records WHERE process_group = ${sqlStr(GROUP)} AND location = 'India' AND machine_class IN (${Object.values(CLASS).map(sqlStr).join(', ')});
  IF n <> ${twins.length} THEN RAISE EXCEPTION 'expected ${twins.length} India Powder Metal machines, found %', n; END IF;
END $powder_metal_check$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${crews.length} USA crews, ${twins.length} India twins)`);
