/**
 * Writes migration 1070 (the additive manufacturing machines at India rates, and the Cleaning machine) from memory/Countries data:
 *   node scripts/generate-additive-machines-migration.js
 * Each India row is its USA twin (migration 793, same machine class and exact name) with the India direct and indirect overhead rates of the
 * export and the India rate of the processes' wage grade (memory/Additive Manufacturing/wage_grade_associations: every process 2 - Casting).
 * The Cleaning machine (Compressed Air Blasting) has no file of its own in memory/Additive Manufacturing; see the migration header.
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1070_additive_machines_india_and_cleaning.sql');

// The machine class migration 793 gave each additive process; Cleaning is new here.
const CLASS = {
  'Metal Sintering': 'metal_sintering', 'Laser Sintering': 'laser_sintering', Printing: 'printing', 'Resin Curing': 'resin_curing',
  'Part Curing': 'part_curing', Breakoff: 'breakoff', 'Powder Loading': 'powder_loading', 'Manual Tool Base Removal': 'manual_tool_base_removal',
  'Power Tool Base Removal': 'power_tool_base_removal', Sieving: 'sieving', Cleaning: 'cleaning',
};
// The India labour rate of wage grade 2 - Casting (USD/hr): the value the 245 India rows of that grade already carry in HR Rates
// (SELECT DISTINCT usd_labor_rate_per_hr FROM mhr_records WHERE location = 'India' AND wage_grade = '2 - Casting').
const INDIA_LABOUR = 2.14;
// The USA labour rate the 793 additive rows carry (their files' Labor Rate, 38.94 USD/hr).
const USA_LABOUR = 38.94;

const grades = readCsv(join(MEMORY, 'Additive Manufacturing/wage_grade_associations (5).csv')).rows;
for (const g of grades) {
  if (CLASS[g['Process Name']] && g['Wage Grade Name'] !== '2 - Casting') throw new Error(`${g['Process Name']} is ${g['Wage Grade Name']}, not 2 - Casting`);
}
const num = (v) => { const n = Number(String(v).replace(/[$,\s]/g, '')); return Number.isFinite(n) ? Math.round(n * 100) / 100 : 0; };
const q = (s) => `$str$${s}$str$`;
const exportRows = (file) => readCsv(join(MEMORY, `Countries data/${file}`)).rows.filter((r) => r['Commodity'] === 'Additive Manufacturing');

const india = exportRows('India_XML_Data_.csv').map((r) => {
  const process = r['Machine Type'];
  const cls = CLASS[process];
  if (!cls) throw new Error(`no machine class for ${process}`);
  return { cls, name: r['name'], direct: num(r['customWorkCenterDirectOverheadRate']), indirect: num(r['customWorkCenterIndirectOverheadRate']), process };
}).sort((a, b) => (a.cls + a.name).localeCompare(b.cls + b.name));
const twins = india.filter((r) => r.cls !== 'cleaning');
const byProcess = {};
for (const r of twins) byProcess[r.process] = (byProcess[r.process] ?? 0) + 1;

const cleanIndia = india.find((r) => r.cls === 'cleaning');
const nl = exportRows('Netherlands_XML_Data_.csv').find((r) => r['Machine Type'] === 'Cleaning');
if (!cleanIndia || !nl) throw new Error('Compressed Air Blasting is not in the India and Netherlands exports');
const spec = {
  price: num(nl['machinePrice']), length: Number(nl['machineLength']), width: Number(nl['machineWidth']), power: Number(nl['machinePower']),
  life: Number(nl['machineLife']), operators: Number(nl['numOperators']), footprint: Number(nl['footprintAllowanceFactor']),
  installation: Number(nl['installationFactor']) * 100, maintenance: Number(nl['annualMaintenanceFactor']) * 100, uptime: Number(nl['machineUptime']) * 100,
  cleaningRate: Number(nl['metalCleaningRate']),
};
const cleaning = { name: nl['name'], usa: { direct: num(nl['customWorkCenterDirectOverheadRate']), indirect: num(nl['customWorkCenterIndirectOverheadRate']) }, india: cleanIndia };

const sql = `-- ============================================================================
-- Migration 1070: Additive Manufacturing machines at India rates, and the Cleaning machine
-- ============================================================================
-- Generated by scripts/generate-additive-machines-migration.js; re-run it and diff instead of editing.
--
-- Migration 793 seeded the 102 additive machines for the USA only, so an additive part priced in India had no machine on any step; and no
-- Cleaning machine at all (the header said the class was registered under Post-Processing; no row ever was), so Cleaning, a step of every
-- additive route, had none anywhere.
--
-- India twins. Source: memory/Countries data/India_XML_Data_.csv, commodity "Additive Manufacturing": each machine's direct and indirect
-- overhead rate (USD/hr, rounded to cents). Labour: the India rate of wage grade 2 - Casting (every additive process's grade,
-- memory/Additive Manufacturing/wage_grade_associations), ${INDIA_LABOUR} USD/hr, the value the India rows of that grade already carry, written to
-- usd_labor_rate_per_hr AND usd_lhr_total (the column the machine selector reads; migration 1061 had to repair the twins that kept the USA
-- value there). ${twins.length} machines, each matched by machine class and exact name to its USA row:
${Object.entries(byProcess).sort().map(([p, n]) => `--   ${p.padEnd(26)}${n} machine(s)`).join('\n')}
--
-- Cleaning: ${cleaning.name}, the process's default machine (memory/Additive Manufacturing/processes.csv). memory/Additive Manufacturing has
-- no machine file for it; the country exports have it (price ${spec.price} USD, ${spec.length} x ${spec.width} mm, ${spec.power} kW, ${spec.life} years, ${spec.operators} operator).
-- India: the India export's rates (${cleaning.india.direct} direct, ${cleaning.india.indirect} indirect USD/hr). USA: there is no USA export (the USA rates
-- are the machine files'); the Netherlands export's rates (${cleaning.usa.direct} direct, ${cleaning.usa.indirect} indirect USD/hr) stand in for them. They are the
-- export closest to the USA files: on the additive machines both have, Manual Breakoff (USA 0.00 / 13.83, Netherlands 0.00 / 13.85) and the
-- Vibratory Compact Sieve (USA 0.34 / 13.88, Netherlands 0.34 / 13.90), within 0.2 %. Labour ${USA_LABOUR} USD/hr (USA), ${INDIA_LABOUR} (India), grade 2 - Casting.
-- The row is cloned from the USA sieve (the same group, grade and source columns) with the Cleaning machine's own values.
--
-- Idempotent: a row already present for a location + machine_class + machine_name is skipped.
-- Verify: SELECT location, machine_class, count(*) FROM mhr_records WHERE process_group = 'Additive Manufacturing' GROUP BY 1, 2 ORDER BY 1, 2;
--   -- expect USA ${twins.length + 1} rows (11 classes), India ${twins.length + 1} rows (11 classes).
-- ============================================================================

DO $additive_machines$
DECLARE
  cols text; sel text; r record; usa_id uuid; n integer := 0; missing text[] := '{}';
BEGIN
  SELECT
    string_agg(quote_ident(c.column_name), ', ' ORDER BY c.ordinal_position),
    string_agg(
      CASE c.column_name
        WHEN 'location'                                THEN '$5'
        WHEN 'country_code'                            THEN '$6'
        WHEN 'machine_class'                           THEN '$7'
        WHEN 'machine_name'                            THEN '$8'
        WHEN 'direct_overhead_rate'                    THEN '$2'
        WHEN 'indirect_overhead_rate'                  THEN '$3'
        WHEN 'benchmark_direct_overhead_rate_usd_hr'   THEN '$2'
        WHEN 'benchmark_indirect_overhead_rate_usd_hr' THEN '$3'
        WHEN 'total_machine_hour_rate'                 THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'mhr_usd_per_hour'                        THEN 'ROUND(($2 + $3)::numeric, 2)'
        WHEN 'usd_labor_rate_per_hr'                   THEN '$4'
        WHEN 'usd_lhr_total'                           THEN '$4'
        WHEN 'benchmark_labor_rate_usd_hr'             THEN '$4'
        WHEN 'benchmark_source_key'                    THEN '$9'
        WHEN 'machine_price_usd'                       THEN 'COALESCE($10, usa_row.machine_price_usd)'
        WHEN 'machine_length_mm'                       THEN 'COALESCE($11, usa_row.machine_length_mm)'
        WHEN 'machine_width_mm'                        THEN 'COALESCE($12, usa_row.machine_width_mm)'
        WHEN 'machine_power_kw'                        THEN 'COALESCE($13, usa_row.machine_power_kw)'
        WHEN 'operators'                               THEN 'COALESCE($14, usa_row.operators)'
        WHEN 'footprint_allowance_factor'              THEN 'COALESCE($15, usa_row.footprint_allowance_factor)'
        WHEN 'specs'                                   THEN 'COALESCE($16, usa_row.specs)'
        WHEN 'id'                                      THEN 'gen_random_uuid()'
        WHEN 'created_at'                              THEN 'now()'
        WHEN 'updated_at'                              THEN 'now()'
        ELSE 'usa_row.' || quote_ident(c.column_name)
      END, ', ' ORDER BY c.ordinal_position
    )
  INTO cols, sel
  FROM information_schema.columns c
  WHERE c.table_schema = 'public' AND c.table_name = 'mhr_records' AND c.is_generated = 'NEVER';

  -- (source class, source name, target location, country, target class, target name, labour, direct, indirect, source key, the Cleaning machine's own values or NULL)
  FOR r IN SELECT * FROM (VALUES
${[
  ...twins.map((t) => `  (${q(t.cls)}, ${q(t.name)}, 'India', 'IN', ${q(t.cls)}, ${q(t.name)}, ${INDIA_LABOUR}, ${t.direct}, ${t.indirect}, ${q(`${t.process}:${t.name}:India`)}, NULL::numeric, NULL::integer, NULL::integer, NULL::numeric, NULL::numeric, NULL::numeric, NULL::jsonb)`),
  ...[['USA', 'US', USA_LABOUR, cleaning.usa], ['India', 'IN', INDIA_LABOUR, cleaning.india]].map(([loc, cc, lab, rates]) =>
    `  ('sieving', ${q('Vibratory Compact Sieve - 500mm Diameter')}, '${loc}', '${cc}', 'cleaning', ${q(cleaning.name)}, ${lab}, ${rates.direct}, ${rates.indirect}, ${q(`Cleaning:${cleaning.name}${loc === 'USA' ? '' : ':India'}`)}, ${spec.price}, ${spec.length}, ${spec.width}, ${spec.power}, ${spec.operators}, ${spec.footprint}, ${q(JSON.stringify({ source: `memory/Countries data (${loc === 'USA' ? 'Netherlands rates for the USA, see migration 1070' : 'India'})`, process: 'Cleaning', machine_life_yr: spec.life, installation_factor_pct: spec.installation, annual_maintenance_factor_pct: spec.maintenance, machine_uptime_pct: spec.uptime, metal_cleaning_rate: spec.cleaningRate }))}::jsonb)`),
].join(',\n')}
  ) AS v(src_class, src_name, location, country, machine_class, machine_name, labor, direct, indirect, source_key, price, length_mm, width_mm, power_kw, operators, footprint, specs)
  LOOP
    SELECT id INTO usa_id FROM mhr_records
    WHERE process_group = 'Additive Manufacturing' AND location = 'USA' AND machine_class = r.src_class AND machine_name = r.src_name
    LIMIT 1;
    IF usa_id IS NULL THEN
      missing := array_append(missing, r.src_class || ':' || r.src_name);
      CONTINUE;
    END IF;
    IF EXISTS (SELECT 1 FROM mhr_records m WHERE m.location = r.location AND m.machine_class = r.machine_class AND m.machine_name = r.machine_name) THEN
      CONTINUE;
    END IF;
    EXECUTE format(
      'INSERT INTO mhr_records (%s) SELECT %s FROM mhr_records usa_row WHERE usa_row.id = $1',
      cols, sel
    ) USING usa_id, r.direct, r.indirect, r.labor, r.location, r.country, r.machine_class, r.machine_name, r.source_key,
            r.price, r.length_mm, r.width_mm, r.power_kw, r.operators, r.footprint, r.specs;
    n := n + 1;
  END LOOP;

  RAISE NOTICE 'Additive Manufacturing rows inserted: %', n;
  IF array_length(missing, 1) > 0 THEN
    RAISE NOTICE 'Additive Manufacturing rows with no USA row (not inserted): %', missing;
  END IF;
END $additive_machines$;

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${twins.length} India twins + Cleaning at USA and India)`);
