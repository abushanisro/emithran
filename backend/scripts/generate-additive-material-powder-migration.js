/**
 * Writes migration 1072 (the additive materials' build properties, staged as a lookup table) from memory/Additive Manufacturing/Raw materials.csv:
 *   node scripts/generate-additive-material-powder-migration.js
 */
const { writeFileSync } = require('fs');
const { join } = require('path');
const { readCsv } = require('../migrations/scripts/lib/memory-machine-seed.js');

const MEMORY = join(__dirname, '../../memory');
const OUT = join(__dirname, '../migrations/1072_additive_material_build_properties.sql');
const KEY = 'additive_tblMaterialBuild';

const num = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const rows = readCsv(join(MEMORY, 'Additive Manufacturing/Raw materials.csv')).rows.map((r) => ({
  'Material Name': r['Name'],
  Grade: r['Source Name'],
  Process: r['Process'],
  'Material Type': r['Material Type'],
  'Tapped Density (kg / m^3)': num(r['Tapped Density (kg / m^3)']),
  'Max Powder Cycles': num(r['Max Powder Cycles']),
  'Recycle Percentage': num(r['Recycle Percentage']),
})).sort((a, b) => (a.Process + a.Grade).localeCompare(b.Process + b.Grade));
const byProcess = {};
for (const r of rows) byProcess[r.Process] = (byProcess[r.Process] ?? 0) + 1;
const raw = JSON.stringify({ rows }, null, 1).replace(/\$/g, '');

const sql = `-- ============================================================================
-- Migration 1072: the additive materials' build properties, staged as a lookup table
-- ============================================================================
-- Generated by scripts/generate-additive-material-powder-migration.js; re-run it and diff instead of editing.
--
-- Migration 855 moved the ${rows.length} additive materials (memory/Additive Manufacturing/Raw materials.csv) into raw_materials with their density and
-- price, but not the columns that say how each one is built: its process (DMLS, SLS, SLA, 3D Printing: which route may build it), its
-- tapped density (the powder bed's density, not the solid's) and, for a polymer powder, how many build cycles the powder survives and the
-- share of the bed that is recycled. Without them an SLS part's powder cost and a material's route cannot be read. They are staged here
-- beside the additive reference data (source version 2026-Additive), keyed by grade (raw_materials.grade), as a table the engine reads like
-- the others.
${Object.entries(byProcess).sort().map(([p, n]) => `--   ${p.padEnd(12)}${n} material(s)`).join('\n')}
--
-- Idempotent: the row is inserted once and never overwritten.
-- ============================================================================

INSERT INTO machining_reference_data (category, source_region, source_version, key, value, notes, raw)
SELECT 'lookup_table', 'USA', '2026-Additive', '${KEY}', '${rows.length}',
  'memory/Additive Manufacturing/Raw materials.csv: each material''s process, tapped density, max powder cycles and recycle percentage',
  $raw$${raw}$raw$::jsonb
WHERE NOT EXISTS (SELECT 1 FROM machining_reference_data WHERE source_version = '2026-Additive' AND key = '${KEY}');

NOTIFY pgrst, 'reload schema';
`;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} materials)`);
